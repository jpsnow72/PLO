/**
 * Attempt to upload one done item's result to the central library and
 * record the outcome on the item. Never throws. Without a runner-config
 * the item is "skipped" (offline mode is a first-class state).
 */
async function attemptItemUpload(item) {
  const config = await loadRunnerConfig(DATA_DIR);
  if (!config) {
    if (item.upload_status !== 'skipped') {
      item.upload_status = 'skipped';
      item.upload_error = null;
      await saveQueue();
    }
    return;
  }
  const entry = await findCatalogEntry(item.spot_id).catch(() => null);
  if (!entry) {
    item.upload_status = 'failed';
    item.upload_error = 'Spot no longer present in the catalog; cannot build the ingest payload.';
    await saveQueue();
    return;
  }
  let result;
  try {
    result = JSON.parse(
      await fs.readFile(path.join(JOBS_DIR, item.job_id, 'result.json'), 'utf8'),
    );
  } catch {
    item.upload_status = 'failed';
    item.upload_error = 'Job result file is missing locally; cannot upload.';
    await saveQueue();
    return;
  }
  const outcome = await attemptUpload({ config, spot: entry, result });
  if (outcome.ok) {
    item.upload_status = 'uploaded';
    item.upload_error = null;
    item.uploaded_at = nowIso();
    item.upload_detail = outcome.status ?? null;
  } else {
    item.upload_status = 'failed';
    item.upload_error = outcome.error;
  }
  await saveQueue();
}

/** Retry uploads for done items that are not yet uploaded. */
async function retryPendingUploads() {
  for (const item of queueState.items) {
    if (item.state === 'done' && item.upload_status !== 'uploaded') {
      await attemptItemUpload(item);
    }
  }
}

// --- Worker -------------------------------------------------------------------

let queueTickRunning = false;

/**
 * One worker pass: settle running items whose jobs have finished, then
 * start queued items up to the concurrency limit. Runs on a 1s timer
 * when QUEUE_ENABLED=1 (and is kicked by queue mutations).
 */
async function queueTick() {
  if (queueTickRunning) return;
  queueTickRunning = true;
  try {
    // Settle: a queue item is done ONLY when its job is done AND the
    // job's library entry exists (runJob writes it before returning).
    for (const item of queueState.items) {
      if (item.state !== 'running' || !item.job_id) continue;
      const job = jobs.get(item.job_id);
      if (!job) {
        // The job registry is in-memory; a missing job here means the
        // process restarted mid-solve (loadQueue already reverts those)
        // or the job vanished — treat as interrupted, never as done.
        item.state = 'queued';
        item.job_id = null;
        item.started_at = null;
        await saveQueue();
        continue;
      }
      if (job.status === 'done') {
        let libraryExists = false;
        try {
          await fs.access(path.join(LIBRARY_DIR, `${job.id}.json`));
          libraryExists = true;
        } catch {
          libraryExists = false;
        }
        if (!libraryExists) {
          item.state = 'failed';
          item.error = 'Job reported done but its library entry is missing; refusing to mark done.';
          item.finished_at = nowIso();
          await saveQueue();
          continue;
        }
        item.state = 'done';
        item.finished_at = nowIso();
        item.nash_distance_pct = job.nash_distance_pct;
        item.iterations = job.iterations;
        item.error = null;
        if (item.upload_status === 'uploaded') item.upload_status = 'pending';
        await saveQueue();
        await attemptItemUpload(item);
      } else if (job.status === 'error') {
        item.state = 'failed';
        item.error = job.error ?? 'Engine job failed';
        item.finished_at = nowIso();
        await saveQueue();
      }
    }
    // Start: fill free slots from the front of the queue.
    if (!queueState.paused) {
      let running = queueState.items.filter((item) => item.state === 'running').length;
      for (const item of queueState.items) {
        if (running >= queueState.concurrency) break;
        if (item.state !== 'queued') continue;
        const entry = await findCatalogEntry(item.spot_id);
        if (!entry) {
          item.state = 'failed';
          item.error = 'Spot not found in the catalog.';
          item.finished_at = nowIso();
          await saveQueue();
          continue;
        }
        try {
          const { spot, meta } = await translateCatalogEntry(entry);
          const job = await submitJob(spot, meta);
          item.state = 'running';
          item.job_id = job.id;
          item.started_at = nowIso();
          item.finished_at = null;
          item.error = null;
          item.upload_status = 'pending';
          running += 1;
          await saveQueue();
        } catch (err) {
          item.state = 'failed';
          item.error = err instanceof Error ? err.message : String(err);
          item.finished_at = nowIso();
          await saveQueue();
        }
      }
    }
  } finally {
    queueTickRunning = false;
  }
}
/**
 * CORS headers for a response. Default: the historical wildcard (fine for
 * reads and same-origin use). When ALLOWED_ORIGIN is configured and the
 * request's Origin matches it exactly, echo that origin and allow
 * credentials, so the hosted UI can send the admin session cookie
 * cross-origin. See README.md ("Admin auth, CORS and cookies") for the
 * limits of that arrangement.
 */
function corsHeaders(req) {
  const origin = req?.headers?.origin;
  if (ALLOWED_ORIGIN && typeof origin === 'string' && origin === ALLOWED_ORIGIN) {
    return {
      'Access-Control-Allow-Origin': origin,
      'Access-Control-Allow-Credentials': 'true',
      Vary: 'Origin',
    };
  }
  return { 'Access-Control-Allow-Origin': '*' };
}

/** Serve a JSON file verbatim with a JSON content type. */
async function sendJsonFile(req, res, file) {
  let raw;
  try {
    raw = await fs.readFile(file, 'utf8');
  } catch {
    sendJson(req, res, 404, { error: `Not found: ${path.basename(file)}` });
    return;
  }
  res.writeHead(200, {
    'Content-Type': 'application/json',
    ...corsHeaders(req),
  });
  res.end(raw);
}

function sendJson(req, res, status, body, extraHeaders = {}) {
  const text = JSON.stringify(body);
  res.writeHead(status, {
    'Content-Type': 'application/json',
    'Content-Length': Buffer.byteLength(text),
    ...corsHeaders(req),
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    ...extraHeaders,
  });
  res.end(text);
}

/**
 * Gate for write endpoints. Returns true when the request may proceed.
 * Otherwise a 401 JSON has already been sent. When auth is disabled the
 * gate is open by definition (local dev mode — see the startup warning).
 */
async function requireAdmin(req, res) {
  if (await isAdminRequest(req)) return true;
  sendJson(req, res, 401, { error: 'Admin login required' });
  return false;
}

function readBody(req) {
  return readBodyWithLimit(req, MAX_BODY_BYTES);
}

/**
 * Read a request body with an explicit byte cap. Rejects with HttpError
 * 413 when the cap is exceeded (checked against Content-Length up front
 * when present, and again while streaming).
 */
function readBodyWithLimit(req, maxBytes) {
  return new Promise((resolve, reject) => {
    const declared = Number(req.headers['content-length']);
    if (Number.isFinite(declared) && declared > maxBytes) {
      reject(new HttpError(413, `Request body too large (limit ${maxBytes} bytes)`));
      req.destroy();
      return;
    }
    const chunks = [];
    let total = 0;
    req.on('data', (chunk) => {
      total += chunk.length;
      if (total > maxBytes) {
        reject(new HttpError(413, `Request body too large (limit ${maxBytes} bytes)`));
        req.destroy();
        return;
      }
      chunks.push(chunk);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url ?? '/', `http://${req.headers.host ?? 'localhost'}`);
  const parts = url.pathname.split('/').filter((p) => p.length > 0);
  try {
    if (req.method === 'OPTIONS') {
      res.writeHead(204, {
        ...corsHeaders(req),
        'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
      });
      res.end();
      return;
    }

    // --- Admin auth ------------------------------------------------------
    if (req.method === 'POST' && url.pathname === '/api/auth/login') {
      if (!AUTH_ENABLED) {
        sendJson(req, res, 400, {
          error:
            'Auth is not enabled on this server (ADMIN_PASSWORD_HASH is not set), so there is nothing to log in to — write endpoints are open (local dev mode).',
        });
        return;
      }
      const text = await readBody(req);
      let body;
      try {
        body = JSON.parse(text);
      } catch {
        sendJson(req, res, 400, { error: 'Body must be valid JSON.' });
        return;
      }
      const password = body && typeof body === 'object' ? body.password : undefined;
      if (typeof password !== 'string' || password.length === 0) {
        sendJson(req, res, 400, { error: 'Body must carry a password string.' });
        return;
      }
      const ok = AUTH_HASH_OK && (await verifyPassword(password, ADMIN_PASSWORD_HASH));
      if (!ok) {
        // Generic message + a small constant delay: no oracle about which
        // part failed, and no fast password-guessing loop.
        await sleep(LOGIN_FAILURE_DELAY_MS);
        sendJson(req, res, 401, { error: 'Invalid password' });
        return;
      }
      const token = await sessionStore.create();
      sendJson(req, res, 200, { admin: true }, {
        'Set-Cookie': sessionCookieValue(token, requestIsSecure(req)),
      });
      return;
    }

    if (req.method === 'POST' && url.pathname === '/api/auth/logout') {
      const token = sessionTokenFrom(req);
      if (token) await sessionStore.delete(token);
      sendJson(req, res, 200, { admin: false }, {
        'Set-Cookie': clearCookieValue(requestIsSecure(req)),
      });
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/auth/me') {
      if (!AUTH_ENABLED) {
        sendJson(req, res, 200, { admin: true, auth_enabled: false });
        return;
      }
      if (await isAdminRequest(req)) {
        sendJson(req, res, 200, { admin: true, auth_enabled: true });
        return;
      }
      sendJson(req, res, 401, { error: 'Not signed in' });
      return;
    }

    if (req.method === 'POST' && url.pathname === '/api/solves') {
      if (!(await requireAdmin(req, res))) return;
      const text = await readBody(req);
      let spot;
      try {
        spot = JSON.parse(text);
      } catch {
        sendJson(req, res, 400, { error: 'Body must be valid JSON (an engine spot).' });
        return;
      }
      const kind = kindForBoard(spot?.board);
      if (kind === null) {
        sendJson(req, res, 400, { error: 'Spot board must have 3, 4 or 5 cards.' });
        return;
      }
      // Optional range-set loading: `oop_range_set` / `ip_range_set` name a
      // preflop set id and replace the raw range array for that side. The
      // expansion happens here, server-side; the engine only ever sees
      // ordinary per-combo range entries.
      //
      // RUN-1 capped expansion: when any of `<side>_range_cap`,
      // `<side>_range_mode`, `<side>_range_seed`, `<side>_range_action`,
      // `<side>_range_base_set` or `<side>_range_base_action` is present,
      // the side expands through expandRangeSetCapped (explicit actions
      // allow sb_play / three_bet / vs_three_bet slices the uncapped v1
      // path refuses); without them the historical uncapped v1 expansion
      // runs unchanged. Either way the expansion summary is recorded on
      // the job (range_expansion) and every helper field is stripped from
      // the spot before it reaches the engine.
      const rangeSets = { oop: null, ip: null };
      const rangeExpansion = { oop: null, ip: null };
      try {
        for (const side of ['oop', 'ip']) {
          const setId = spot[`${side}_range_set`];
          const capFields = [
            'range_cap',
            'range_mode',
            'range_seed',
            'range_action',
            'range_base_set',
            'range_base_action',
          ].map((f) => `${side}_${f}`);
          if (setId === undefined || setId === null) {
            for (const f of capFields) delete spot[f];
            continue;
          }
          if (typeof setId !== 'string' || setId.length === 0) {
            throw new HttpError(400, `${side}_range_set must be a preflop range set id string`);
          }
          if (spot[`${side}_range`] !== undefined || spot[side] !== undefined) {
            throw new HttpError(
              400,
              `Provide either ${side}_range or ${side}_range_set for the ${side.toUpperCase()} side, not both`,
            );
          }
          const useCapped = capFields.some((f) => spot[f] !== undefined && spot[f] !== null);
          if (useCapped) {
            const expanded = await expandRangeSetCapped({
              setId,
              action:
                typeof spot[`${side}_range_action`] === 'string'
                  ? spot[`${side}_range_action`]
                  : null,
              cap: spot[`${side}_range_cap`] ?? null,
              mode: spot[`${side}_range_mode`] ?? 'top',
              seed: spot[`${side}_range_seed`] ?? null,
              baseSetId: spot[`${side}_range_base_set`] ?? null,
              baseAction: spot[`${side}_range_base_action`] ?? 'raise',
            });
            spot[`${side}_range`] = expanded.range;
            rangeExpansion[side] = {
              set: setId,
              action: expanded.action,
              cap: spot[`${side}_range_cap`] ?? null,
              mode: expanded.mode,
              seed: expanded.seed,
              kept_combos: expanded.kept_combos,
              total_combos: expanded.total_combos,
              coverage_pct: expanded.coverage_pct,
              base_set: expanded.base_set,
              base_action: expanded.base_action,
            };
          } else {
            const expanded = await expandRangeSet(setId);
            spot[`${side}_range`] = expanded.range;
            rangeExpansion[side] = {
              set: setId,
              action: expanded.action,
              cap: null,
              mode: 'all',
              seed: null,
              kept_combos: expanded.combos,
              total_combos: expanded.combos,
              coverage_pct: 100,
              base_set: null,
              base_action: null,
            };
          }
          rangeSets[side] = setId;
          delete spot[`${side}_range_set`];
          for (const f of capFields) delete spot[f];
        }
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      const job = await submitJob(spot, {
        oop_range_set: rangeSets.oop,
        ip_range_set: rangeSets.ip,
        range_expansion: rangeExpansion.oop || rangeExpansion.ip ? rangeExpansion : null,
      });
      sendJson(req, res, 202, publicJob(job));
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'solves' && parts[2]) {
      const job = jobs.get(parts[2]);
      if (!job) {
        sendJson(req, res, 404, { error: 'Unknown job id' });
        return;
      }
      if (parts[3] === 'result') {
        if (job.status !== 'done') {
          sendJson(req, res, 409, { error: `Job is ${job.status}, no result yet` });
          return;
        }
        const raw = await fs.readFile(path.join(JOBS_DIR, job.id, 'result.json'), 'utf8');
        res.writeHead(200, {
          'Content-Type': 'application/json',
          ...corsHeaders(req),
        });
        res.end(raw);
        return;
      }
      sendJson(req, res, 200, publicJob(job));
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/jobs') {
      sendJson(req, res, 200, { jobs: [...jobs.values()].map(publicJob) });
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/library') {
      sendJson(req, res, 200, { library: await listLibrary() });
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'library' && parts[2]) {
      if (!/^[A-Za-z0-9_-]+$/.test(parts[2])) {
        sendJson(req, res, 400, { error: 'Bad library id' });
        return;
      }
      const file = path.join(LIBRARY_DIR, `${parts[2]}.json`);
      try {
        const raw = await fs.readFile(file, 'utf8');
        res.writeHead(200, {
          'Content-Type': 'application/json',
          ...corsHeaders(req),
        });
        res.end(raw);
      } catch {
        sendJson(req, res, 404, { error: 'Unknown library id' });
      }
      return;
    }

    // Ingest a finished solve produced elsewhere (the local PC runner).
    // Body: { spot: {...catalog metadata, incl. id}, result: <engine JSON> }.
    // Stored exactly like a job-produced library entry, plus
    // source: "local-runner", the spot metadata, and a content hash that
    // makes re-ingesting the identical solve a no-op ({status: "exists"}).
    if (req.method === 'POST' && url.pathname === '/api/library/ingest') {
      if (!(await requireAdmin(req, res))) return;
      try {
        const text = await readBodyWithLimit(req, INGEST_MAX_BYTES);
        let body;
        try {
          body = JSON.parse(text);
        } catch {
          throw new HttpError(400, 'Body must be valid JSON: { spot, result }.');
        }
        const spot = body && typeof body === 'object' ? body.spot : undefined;
        const result = body && typeof body === 'object' ? body.result : undefined;
        if (!spot || typeof spot !== 'object' || Array.isArray(spot)) {
          throw new HttpError(400, 'Body must carry a spot object (catalog-shaped metadata).');
        }
        if (typeof spot.id !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9_-]*$/.test(spot.id)) {
          throw new HttpError(400, 'spot.id must be a non-empty id string (letters, digits, - and _).');
        }
        if (!result || typeof result !== 'object' || Array.isArray(result)) {
          throw new HttpError(422, 'Body must carry a result object (the engine solve JSON).');
        }
        const nash = result?.exploitability?.nash_distance_pct;
        if (typeof result.board !== 'string' || typeof nash !== 'number' || typeof result.iterations !== 'number') {
          throw new HttpError(
            422,
            'result is not a recognisable engine solve (needs board, exploitability.nash_distance_pct and iterations).',
          );
        }
        const contentHash = createHash('sha256')
          .update(spot.id, 'utf8')
          .update('\n')
          .update(JSON.stringify(result), 'utf8')
          .digest('hex');
        await fs.mkdir(LIBRARY_DIR, { recursive: true });
        const metaPath = path.join(LIBRARY_DIR, `${spot.id}.meta.json`);
        let priorMeta = null;
        try {
          priorMeta = JSON.parse(await fs.readFile(metaPath, 'utf8'));
        } catch {
          priorMeta = null;
        }
        if (priorMeta && priorMeta.content_hash === contentHash) {
          sendJson(req, res, 200, {
            status: 'exists',
            id: spot.id,
            nash_distance_pct: nash,
            iterations: result.iterations,
          });
          return;
        }
        const kind = ['river', 'turn', 'flop'].includes(spot.kind)
          ? spot.kind
          : kindForBoard(result.board) ?? 'river';
        const meta = {
          id: spot.id,
          name: typeof spot.name === 'string' && spot.name.length > 0 ? spot.name : `Solve · ${result.board}`,
          kind,
          street: kind,
          board: result.board,
          oop_range_set: typeof spot.oop_range_set === 'string' ? spot.oop_range_set : null,
          ip_range_set: typeof spot.ip_range_set === 'string' ? spot.ip_range_set : null,
          nash_distance_pct: nash,
          iterations: result.iterations,
          finished_at: nowIso(),
          source: 'local-runner',
          spot,
          content_hash: contentHash,
        };
        await fs.writeFile(path.join(LIBRARY_DIR, `${spot.id}.json`), JSON.stringify(result));
        await fs.writeFile(metaPath, JSON.stringify(meta, null, 2));
        sendJson(req, res, priorMeta ? 200 : 201, {
          status: priorMeta ? 'updated' : 'created',
          id: spot.id,
          nash_distance_pct: nash,
          iterations: result.iterations,
        });
        return;
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
    }

    if (req.method === 'GET' && url.pathname === '/api/preflop/index') {
      await sendJsonFile(req, res, path.join(PREFLOP_DIR, 'index.json'));
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/preflop/class-table') {
      const file = path.join(PREFLOP_DIR, 'class-table.json');
      try {
        await fs.access(file);
      } catch {
        sendJson(req, res, 404, {
          error:
            'Class table not generated yet: data/preflop/class-table.json is written by the engine build-ranges tool on a host.',
        });
        return;
      }
      await sendJsonFile(req, res, file);
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'preflop' && parts[2] === 'sets' && parts[3]) {
      let entry;
      try {
        entry = await findPreflopSetEntry(parts[3]);
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      if (!entry) {
        sendJson(req, res, 404, { error: `Unknown preflop range set id "${parts[3]}"` });
        return;
      }
      const file = preflopEntryPath(entry);
      if (!file) {
        sendJson(req, res, 500, { error: `Preflop index entry for "${parts[3]}" has an unsafe path` });
        return;
      }
      await sendJsonFile(req, res, file);
      return;
    }

    // --- Spot catalog -----------------------------------------------------
    // Public read: the catalog entries, each annotated with whether the
    // spot is already in the LOCAL library (by spot id — job-produced
    // entries carry their spot id in meta; ingested entries are filed
    // under it) and its queue state when queued here.
    if (req.method === 'GET' && url.pathname === '/api/catalog') {
      try {
        const catalog = await loadCatalog();
        const library = await listLibrary();
        const present = new Set();
        for (const item of library) {
          present.add(item.id);
          if (item.spot_id) present.add(item.spot_id);
        }
        const entries = catalog.entries.map((entry) => {
          const item = queueItemFor(entry.id);
          return {
            ...entry,
            library_status: present.has(entry.id) ? 'present' : 'absent',
            queue_status: item ? item.state : null,
            queue_upload_status: item ? item.upload_status : null,
          };
        });
        sendJson(req, res, 200, {
          name: catalog.name ?? null,
          schema_version: catalog.schema_version ?? null,
          summary: catalog.summary ?? null,
          entries,
        });
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      return;
    }

    // --- Solve queue --------------------------------------------------------
    if (req.method === 'GET' && url.pathname === '/api/queue') {
      sendJson(req, res, 200, {
        items: queueState.items,
        concurrency: queueState.concurrency,
        paused: queueState.paused,
        enabled: QUEUE_ENABLED,
      });
      return;
    }

    if (req.method === 'POST' && url.pathname === '/api/queue') {
      if (!(await requireAdmin(req, res))) return;
      const text = await readBody(req);
      let body;
      try {
        body = JSON.parse(text);
      } catch {
        sendJson(req, res, 400, { error: 'Body must be valid JSON: { spot_ids: [...] }.' });
        return;
      }
      const spotIds = body && typeof body === 'object' ? body.spot_ids : undefined;
      if (!Array.isArray(spotIds) || spotIds.some((id) => typeof id !== 'string')) {
        sendJson(req, res, 400, { error: 'Body must carry spot_ids: an array of catalog spot id strings.' });
        return;
      }
      let catalog;
      try {
        catalog = await loadCatalog();
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      const known = new Set(catalog.entries.map((entry) => entry.id));
      const unknown = [...new Set(spotIds.filter((id) => !known.has(id)))];
      if (unknown.length > 0) {
        sendJson(req, res, 400, {
          error: `Unknown catalog spot id(s): ${unknown.join(', ')}`,
          unknown,
        });
        return;
      }
      const added = [];
      const skipped = [];
      for (const spotId of new Set(spotIds)) {
        const existing = queueItemFor(spotId);
        if (existing && existing.state === 'failed') {
          // Re-adding a failed spot is the retry path: reset it in place.
          existing.state = 'queued';
          existing.job_id = null;
          existing.started_at = null;
          existing.finished_at = null;
          existing.error = null;
          existing.upload_status = 'pending';
          added.push(spotId);
          continue;
        }
        if (existing) {
          skipped.push({ spot_id: spotId, reason: `already ${existing.state}` });
          continue;
        }
        queueState.items.push({
          spot_id: spotId,
          state: 'queued',
          added_at: nowIso(),
          started_at: null,
          finished_at: null,
          job_id: null,
          upload_status: 'pending',
          error: null,
        });
        added.push(spotId);
      }
      await saveQueue();
      if (QUEUE_ENABLED) void queueTick();
      sendJson(req, res, 200, { added, skipped, items: queueState.items });
      return;
    }

    if (req.method === 'POST' && url.pathname === '/api/queue/control') {
      if (!(await requireAdmin(req, res))) return;
      const text = await readBody(req);
      let body;
      try {
        body = JSON.parse(text);
      } catch {
        sendJson(req, res, 400, { error: 'Body must be valid JSON: { action, ... }.' });
        return;
      }
      const action = body && typeof body === 'object' ? body.action : undefined;
      if (action === 'pause' || action === 'resume') {
        queueState.paused = action === 'pause';
        await saveQueue();
        if (QUEUE_ENABLED && !queueState.paused) void queueTick();
        sendJson(req, res, 200, {
          items: queueState.items,
          concurrency: queueState.concurrency,
          paused: queueState.paused,
          enabled: QUEUE_ENABLED,
        });
        return;
      }
      if (action === 'set_concurrency') {
        const value = body.value;
        if (!Number.isInteger(value) || value < 1 || value > 8) {
          sendJson(req, res, 400, { error: 'set_concurrency needs value: an integer between 1 and 8.' });
          return;
        }
        queueState.concurrency = value;
        await saveQueue();
        if (QUEUE_ENABLED) void queueTick();
        sendJson(req, res, 200, {
          items: queueState.items,
          concurrency: queueState.concurrency,
          paused: queueState.paused,
          enabled: QUEUE_ENABLED,
        });
        return;
      }
      if (action === 'remove') {
        const spotId = body.spot_id;
        if (typeof spotId !== 'string' || spotId.length === 0) {
          sendJson(req, res, 400, { error: 'remove needs spot_id: a queue item spot id.' });
          return;
        }
        const item = queueItemFor(spotId);
        if (!item) {
          sendJson(req, res, 404, { error: `No queue item for spot "${spotId}"` });
          return;
        }
        if (item.state === 'running') {
          sendJson(req, res, 409, {
            error: `Spot "${spotId}" is running; pause the queue and let it finish, or restart the server (running items revert to queued).`,
          });
          return;
        }
        queueState.items = queueState.items.filter((i) => i.spot_id !== spotId);
        await saveQueue();
        sendJson(req, res, 200, {
          items: queueState.items,
          concurrency: queueState.concurrency,
          paused: queueState.paused,
          enabled: QUEUE_ENABLED,
        });
        return;
      }
      sendJson(req, res, 400, {
        error: 'action must be one of "pause", "resume", "remove", "set_concurrency".',
      });
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/health') {
      sendJson(req, res, 200, {
        ok: true,
        engine_bin: ENGINE_BIN,
        data_dir: DATA_DIR,
        preflop_dir: PREFLOP_DIR,
        auth_enabled: AUTH_ENABLED,
        queue_enabled: QUEUE_ENABLED,
        catalog_path: CATALOG_PATH,
      });
      return;
    }

    sendJson(req, res, 404, { error: 'Not found' });
  } catch (err) {
    sendJson(req, res, 500, { error: err instanceof Error ? err.message : 'Internal error' });
  }
});

