// --- Admin auth -----------------------------------------------------------
// Enabled iff ADMIN_PASSWORD_HASH holds a parseable scrypt hash. A value
// that is set but malformed fails CLOSED: auth stays "enabled" (writes
// stay gated, every login fails) and the misconfiguration is logged.
const ADMIN_PASSWORD_HASH = process.env.ADMIN_PASSWORD_HASH ?? '';
const AUTH_ENABLED = ADMIN_PASSWORD_HASH.length > 0;
const AUTH_HASH_OK = AUTH_ENABLED && parsePasswordHash(ADMIN_PASSWORD_HASH) !== null;
const sessionStore = new SessionStore(path.join(DATA_DIR, 'auth-sessions.json'));
const LOGIN_FAILURE_DELAY_MS = 250;

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/** The raw session token from the request's cookie, or null. */
function sessionTokenFrom(req) {
  return parseCookies(req).get(SESSION_COOKIE) ?? null;
}

/** True when the request carries a live admin session. */
async function isAdminRequest(req) {
  if (!AUTH_ENABLED) return true; // dev mode: writes are open (see startup warning)
  const token = sessionTokenFrom(req);
  if (!token) return false;
  return sessionStore.has(token);
}

/** @type {Map<string, object>} */
const jobs = new Map();
let jobChain = Promise.resolve();

function nowIso() {
  return new Date().toISOString();
}

function boardCardCount(board) {
  if (typeof board !== 'string') return 0;
  return board.split(/[\s,]+/).filter((t) => t.trim().length > 0).length;
}

function kindForBoard(board) {
  const n = boardCardCount(board);
  if (n === 5) return 'river';
  if (n === 4) return 'turn';
  if (n === 3) return 'flop';
  return null;
}

async function writeJobFile(job) {
  const dir = path.join(JOBS_DIR, job.id);
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, 'job.json'), JSON.stringify(job, null, 2));
}

async function runJob(job, spot) {
  job.status = 'running';
  await writeJobFile(job);
  const dir = path.join(JOBS_DIR, job.id);
  const spotPath = path.join(dir, 'spot.json');
  const resultPath = path.join(dir, 'result.json');
  await fs.writeFile(spotPath, JSON.stringify(spot, null, 2));

  const binaryName =
    job.kind === 'flop' ? 'solve-flop' : job.kind === 'turn' ? 'solve-turn' : 'solve-river';
  const binary = path.join(ENGINE_BIN, binaryName);
  try {
    await fs.access(binary);
  } catch {
    job.status = 'error';
    job.error = `Engine binary not found at ${binary}. Build the engine (cargo build --release) or set ENGINE_BIN.`;
    job.finished_at = nowIso();
    await writeJobFile(job);
    return;
  }

  const code = await new Promise((resolve) => {
    const child = spawn(binary, [spotPath, resultPath], { stdio: ['ignore', 'pipe', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', (chunk) => {
      stderr += String(chunk);
    });
    const timer = setTimeout(() => {
      child.kill('SIGKILL');
    }, JOB_TIMEOUT_MS);
    child.on('error', () => {
      clearTimeout(timer);
      resolve(-1);
    });
    child.on('close', (exitCode) => {
      clearTimeout(timer);
      job.stderr_tail = stderr.slice(-2000);
      resolve(exitCode ?? -1);
    });
  });

  if (code !== 0) {
    job.status = 'error';
    job.error = `Engine exited with code ${code}. ${job.stderr_tail ?? ''}`.trim();
    job.finished_at = nowIso();
    await writeJobFile(job);
    return;
  }

  try {
    const raw = await fs.readFile(resultPath, 'utf8');
    const result = JSON.parse(raw);
    job.nash_distance_pct = result?.exploitability?.nash_distance_pct ?? null;
    job.iterations = result?.iterations ?? null;
    job.status = 'done';
    job.finished_at = nowIso();
    // Publish into the library.
    await fs.mkdir(LIBRARY_DIR, { recursive: true });
    await fs.writeFile(path.join(LIBRARY_DIR, `${job.id}.json`), raw);
    await fs.writeFile(
      path.join(LIBRARY_DIR, `${job.id}.meta.json`),
      JSON.stringify(
        {
          id: job.id,
          name: job.name,
          kind: job.kind,
          street: job.kind,
          board: job.board,
          oop_range_set: job.oop_range_set ?? null,
          ip_range_set: job.ip_range_set ?? null,
          nash_distance_pct: job.nash_distance_pct,
          iterations: job.iterations,
          finished_at: job.finished_at,
        },
        null,
        2,
      ),
    );
  } catch (err) {
    job.status = 'error';
    job.error = `Could not read engine result: ${err instanceof Error ? err.message : String(err)}`;
    job.finished_at = nowIso();
  }
  await writeJobFile(job);
}

function publicJob(job) {
  const { stderr_tail, ...rest } = job;
  return rest;
}

async function listLibrary() {
  await fs.mkdir(LIBRARY_DIR, { recursive: true });
  const files = (await fs.readdir(LIBRARY_DIR)).filter(
    (f) => f.endsWith('.json') && !f.endsWith('.meta.json'),
  );
  const items = [];
  for (const file of files) {
    const id = file.replace(/\.json$/, '');
    const full = path.join(LIBRARY_DIR, file);
    try {
      const raw = await fs.readFile(full, 'utf8');
      const result = JSON.parse(raw);
      let meta = {};
      try {
        meta = JSON.parse(await fs.readFile(path.join(LIBRARY_DIR, `${id}.meta.json`), 'utf8'));
      } catch {
        meta = {};
      }
      const stat = await fs.stat(full);
      items.push({
        id,
        name: meta.name ?? `Solve · ${result.board ?? id}`,
        kind: meta.kind ?? meta.street ?? kindForBoard(result.board) ?? 'river',
        board: result.board ?? '',
        oop_range_set: meta.oop_range_set ?? null,
        ip_range_set: meta.ip_range_set ?? null,
        nash_distance_pct:
          result?.exploitability?.nash_distance_pct ?? meta.nash_distance_pct ?? null,
        iterations: result?.iterations ?? meta.iterations ?? null,
        finished_at: meta.finished_at ?? null,
        size_bytes: stat.size,
      });
    } catch {
      // Skip unreadable entries rather than failing the whole list.
    }
  }
  items.sort((a, b) => String(b.finished_at ?? '').localeCompare(String(a.finished_at ?? '')));
  return items;
}

// ---------------------------------------------------------------------------
// Preflop range sets (data/preflop/)
//
// A range set document maps canonical hand-class keys (a representative
// combo whose suits are labelled by first occurrence, e.g. "As Ah Ks Kh")
// to per-action frequencies. The concrete combos of a class are exactly
// the distinct suit-permutation images of the representative: apply all
// 24 permutations of the four suits, normalise each image by sorting its
// cards (rank descending, then suit in s/h/d/c order) and dedupe. The
// size of that set is the class multiplicity — summing it over a real set
// file reproduces the set's combo-weighted action totals exactly (e.g.
// the 6-max BTN RFI set yields 270,725 combos and 49.0% raise).
// ---------------------------------------------------------------------------

const SUIT_ORDER = ['s', 'h', 'd', 'c'];
const RANK_VALUE = {
  A: 14, K: 13, Q: 12, J: 11, T: 10, 9: 9, 8: 8, 7: 7, 6: 6, 5: 5, 4: 4, 3: 3, 2: 2,
};

function suitPermutations() {
  const perms = [];
  const used = [false, false, false, false];
  const current = [];
  const walk = () => {
    if (current.length === 4) {
      perms.push([...current]);
      return;
    }
    for (let i = 0; i < 4; i += 1) {
      if (used[i]) continue;
      used[i] = true;
      current.push(SUIT_ORDER[i]);
      walk();
      current.pop();
      used[i] = false;
    }
  };
  walk();
  return perms;
}
const SUIT_PERMS = suitPermutations();

/** All concrete combos of the class named by a canonical representative key. */
function classCombos(key) {
  const cards = key.split(' ').map((tok) => ({ rank: tok[0], suit: tok[1] }));
  const seen = new Set();
  for (const perm of SUIT_PERMS) {
    const mapping = { s: perm[0], h: perm[1], d: perm[2], c: perm[3] };
    const mapped = cards.map((c) => ({ rank: c.rank, suit: mapping[c.suit] }));
    mapped.sort(
      (a, b) =>
        RANK_VALUE[b.rank] - RANK_VALUE[a.rank] ||
        SUIT_ORDER.indexOf(a.suit) - SUIT_ORDER.indexOf(b.suit),
    );
    seen.add(mapped.map((c) => `${c.rank}${c.suit}`).join(' '));
  }
  return [...seen];
}

function formatWeight(freq) {
  return String(Number(freq.toFixed(6)));
}

class HttpError extends Error {
  constructor(status, message) {
    super(message);
    this.status = status;
  }
}

/** @type {object | null} */
let preflopIndexCache = null;
/** @type {Map<string, object>} */
const preflopSetCache = new Map();

async function loadPreflopIndex() {
  if (preflopIndexCache) return preflopIndexCache;
  let parsed;
  try {
    parsed = JSON.parse(await fs.readFile(path.join(PREFLOP_DIR, 'index.json'), 'utf8'));
  } catch {
    throw new HttpError(500, `Preflop index not readable at ${path.join(PREFLOP_DIR, 'index.json')}`);
  }
  if (!parsed || !Array.isArray(parsed.rangesets)) {
    throw new HttpError(500, 'Preflop index is malformed (no rangesets array)');
  }
  preflopIndexCache = parsed;
  return parsed;
}

async function findPreflopSetEntry(id) {
  const index = await loadPreflopIndex();
  return index.rangesets.find((entry) => entry && entry.id === id) ?? null;
}

/** Resolve an index entry's path inside PREFLOP_DIR (never user-controlled). */
function preflopEntryPath(entry) {
  const resolved = path.resolve(PREFLOP_DIR, String(entry.path ?? ''));
  if (!resolved.startsWith(PREFLOP_DIR + path.sep)) return null;
  return resolved;
}

async function loadPreflopSet(id) {
  if (preflopSetCache.has(id)) return preflopSetCache.get(id);
  const entry = await findPreflopSetEntry(id);
  if (!entry) {
    throw new HttpError(400, `Unknown preflop range set id "${id}" (not in the preflop index)`);
  }
  const file = preflopEntryPath(entry);
  if (!file) throw new HttpError(500, `Preflop index entry for "${id}" has an unsafe path`);
  let doc;
  try {
    doc = JSON.parse(await fs.readFile(file, 'utf8'));
  } catch {
    throw new HttpError(500, `Preflop range set "${id}" is not readable at ${file}`);
  }
  if (!doc || typeof doc.hands !== 'object' || doc.hands === null) {
    throw new HttpError(500, `Preflop range set "${id}" is malformed (no hands object)`);
  }
  preflopSetCache.set(id, doc);
  return doc;
}

/**
 * The action whose frequencies define the continuing range when a set is
 * loaded into a solve. v1 supports exactly the contexts where that range
 * is well-defined:
 *   - `rfi` sets:    the opening range = hands' `raise` frequencies.
 *   - `vs_rfi` sets: the continuing range vs an open = hands' `call`
 *                    frequencies (the 3-bet slice is a different, narrower
 *                    range and is NOT silently substituted).
 * Any other context (sb_play, three_bet, ...) is rejected with 422.
 */
function solveActionForSet(doc) {
  if (doc.context === 'rfi') return 'raise';
  if (doc.context === 'vs_rfi') return 'call';
  return null;
}

/**
 * Expand a range set into engine range entries ("As Ah Kd Qc:0.5", ...).
 * Every concrete combo of a class gets the class's frequency for the
 * set's solve action; classes with zero frequency for that action are
 * omitted. Returns { range, action, combos }.
 */
async function expandRangeSet(id) {
  const doc = await loadPreflopSet(id);
  const action = solveActionForSet(doc);
  if (action === null) {
    throw new HttpError(
      422,
      `Preflop range set "${id}" has context "${doc.context}", which cannot feed a solve in v1. ` +
        'Only RFI sets (their raise range) and vs-RFI sets (their call range) have a well-defined continuing range.',
    );
  }
  const range = [];
  for (const [key, actions] of Object.entries(doc.hands)) {
    const freq = actions && typeof actions === 'object' ? actions[action] : undefined;
    if (typeof freq !== 'number' || !(freq > 0)) continue;
    const weight = formatWeight(freq);
    for (const combo of classCombos(key)) {
      range.push(`${combo}:${weight}`);
    }
  }
  if (range.length === 0) {
    throw new HttpError(422, `Preflop range set "${id}" expands to an empty ${action} range`);
  }
  return { range, action, combos: range.length };
}

/**
 * CORS headers for a response. Default: the historical wildcard (fine for
 * reads and same-origin use). When ALLOWED_ORIGIN is configured and the
 * request's Origin matches it exactly, echo that origin and allow
 * credentials, so the hosted UI can send the admin session cookie
 * cross-origin. See README.md ("Admin auth, CORS and cookies") for the
 * limits of that arrangement.
 */
function corsHeaders(req) {
  const origin = req?.headers?.origin;
  if (ALLOWED_ORIGIN && typeof origin === 'string' && origin === ALLOWED_ORIGIN) {
    return {
      'Access-Control-Allow-Origin': origin,
      'Access-Control-Allow-Credentials': 'true',
      Vary: 'Origin',
    };
  }
  return { 'Access-Control-Allow-Origin': '*' };
}

/** Serve a JSON file verbatim with a JSON content type. */
async function sendJsonFile(req, res, file) {
  let raw;
  try {
    raw = await fs.readFile(file, 'utf8');
  } catch {
    sendJson(req, res, 404, { error: `Not found: ${path.basename(file)}` });
    return;
  }
  res.writeHead(200, {
    'Content-Type': 'application/json',
    ...corsHeaders(req),
  });
  res.end(raw);
}

function sendJson(req, res, status, body, extraHeaders = {}) {
  const text = JSON.stringify(body);
  res.writeHead(status, {
    'Content-Type': 'application/json',
    'Content-Length': Buffer.byteLength(text),
    ...corsHeaders(req),
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    ...extraHeaders,
  });
  res.end(text);
}

/**
 * Gate for write endpoints. Returns true when the request may proceed.
 * Otherwise a 401 JSON has already been sent. When auth is disabled the
 * gate is open by definition (local dev mode — see the startup warning).
 */
async function requireAdmin(req, res) {
  if (await isAdminRequest(req)) return true;
  sendJson(req, res, 401, { error: 'Admin login required' });
  return false;
}

function readBody(req) {
  return readBodyWithLimit(req, MAX_BODY_BYTES);
}

/**
 * Read a request body with an explicit byte cap. Rejects with HttpError
 * 413 when the cap is exceeded (checked against Content-Length up front
 * when present, and again while streaming).
 */
function readBodyWithLimit(req, maxBytes) {
  return new Promise((resolve, reject) => {
    const declared = Number(req.headers['content-length']);
    if (Number.isFinite(declared) && declared > maxBytes) {
      reject(new HttpError(413, `Request body too large (limit ${maxBytes} bytes)`));
      req.destroy();
      return;
    }
    const chunks = [];
    let total = 0;
    req.on('data', (chunk) => {
      total += chunk.length;
      if (total > maxBytes) {
        reject(new HttpError(413, `Request body too large (limit ${maxBytes} bytes)`));
        req.destroy();
        return;
      }
      chunks.push(chunk);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url ?? '/', `http://${req.headers.host ?? 'localhost'}`);
  const parts = url.pathname.split('/').filter((p) => p.length > 0);
  try {
    if (req.method === 'OPTIONS') {
      res.writeHead(204, {
        ...corsHeaders(req),
        'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
      });
      res.end();
      return;
    }

    // --- Admin auth ------------------------------------------------------
    if (req.method === 'POST' && url.pathname === '/api/auth/login') {
      if (!AUTH_ENABLED) {
        sendJson(req, res, 400, {
          error:
            'Auth is not enabled on this server (ADMIN_PASSWORD_HASH is not set), so there is nothing to log in to — write endpoints are open (local dev mode).',
        });
        return;
      }
      const text = await readBody(req);
      let body;
      try {
        body = JSON.parse(text);
      } catch {
        sendJson(req, res, 400, { error: 'Body must be valid JSON.' });
        return;
      }
      const password = body && typeof body === 'object' ? body.password : undefined;
      if (typeof password !== 'string' || password.length === 0) {
        sendJson(req, res, 400, { error: 'Body must carry a password string.' });
        return;
      }
      const ok = AUTH_HASH_OK && (await verifyPassword(password, ADMIN_PASSWORD_HASH));
      if (!ok) {
        // Generic message + a small constant delay: no oracle about which
        // part failed, and no fast password-guessing loop.
        await sleep(LOGIN_FAILURE_DELAY_MS);
        sendJson(req, res, 401, { error: 'Invalid password' });
        return;
      }
      const token = await sessionStore.create();
      sendJson(req, res, 200, { admin: true }, {
        'Set-Cookie': sessionCookieValue(token, requestIsSecure(req)),
      });
      return;
    }

    if (req.method === 'POST' && url.pathname === '/api/auth/logout') {
      const token = sessionTokenFrom(req);
      if (token) await sessionStore.delete(token);
      sendJson(req, res, 200, { admin: false }, {
        'Set-Cookie': clearCookieValue(requestIsSecure(req)),
      });
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/auth/me') {
      if (!AUTH_ENABLED) {
        sendJson(req, res, 200, { admin: true, auth_enabled: false });
        return;
      }
      if (await isAdminRequest(req)) {
        sendJson(req, res, 200, { admin: true, auth_enabled: true });
        return;
      }
      sendJson(req, res, 401, { error: 'Not signed in' });
      return;
    }

    if (req.method === 'POST' && url.pathname === '/api/solves') {
      if (!(await requireAdmin(req, res))) return;
      const text = await readBody(req);
      let spot;
      try {
        spot = JSON.parse(text);
      } catch {
        sendJson(req, res, 400, { error: 'Body must be valid JSON (an engine spot).' });
        return;
      }
      const kind = kindForBoard(spot?.board);
      if (kind === null) {
        sendJson(req, res, 400, { error: 'Spot board must have 3, 4 or 5 cards.' });
        return;
      }
      // Optional range-set loading: `oop_range_set` / `ip_range_set` name a
      // preflop set id and replace the raw range array for that side. The
      // expansion happens here, server-side; the engine only ever sees
      // ordinary per-combo range entries.
      const rangeSets = { oop: null, ip: null };
      try {
        for (const side of ['oop', 'ip']) {
          const setId = spot[`${side}_range_set`];
          if (setId === undefined || setId === null) continue;
          if (typeof setId !== 'string' || setId.length === 0) {
            throw new HttpError(400, `${side}_range_set must be a preflop range set id string`);
          }
          if (spot[`${side}_range`] !== undefined || spot[side] !== undefined) {
            throw new HttpError(
              400,
              `Provide either ${side}_range or ${side}_range_set for the ${side.toUpperCase()} side, not both`,
            );
          }
          const expanded = await expandRangeSet(setId);
          spot[`${side}_range`] = expanded.range;
          rangeSets[side] = setId;
          delete spot[`${side}_range_set`];
        }
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      const job = {
        id: randomUUID().slice(0, 8),
        status: 'queued',
        kind,
        board: spot.board,
        name: `Custom solve · ${spot.board}`,
        oop_range_set: rangeSets.oop,
        ip_range_set: rangeSets.ip,
        created_at: nowIso(),
        finished_at: null,
        nash_distance_pct: null,
        iterations: null,
        error: null,
      };
      jobs.set(job.id, job);
      await writeJobFile(job);
      // Serial queue: one solve at a time.
      jobChain = jobChain.then(() => runJob(job, spot)).catch(() => undefined);
      sendJson(req, res, 202, publicJob(job));
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'solves' && parts[2]) {
      const job = jobs.get(parts[2]);
      if (!job) {
        sendJson(req, res, 404, { error: 'Unknown job id' });
        return;
      }
      if (parts[3] === 'result') {
        if (job.status !== 'done') {
          sendJson(req, res, 409, { error: `Job is ${job.status}, no result yet` });
          return;
        }
        const raw = await fs.readFile(path.join(JOBS_DIR, job.id, 'result.json'), 'utf8');
        res.writeHead(200, {
          'Content-Type': 'application/json',
          ...corsHeaders(req),
        });
        res.end(raw);
        return;
      }
      sendJson(req, res, 200, publicJob(job));
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/jobs') {
      sendJson(req, res, 200, { jobs: [...jobs.values()].map(publicJob) });
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/library') {
      sendJson(req, res, 200, { library: await listLibrary() });
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'library' && parts[2]) {
      if (!/^[A-Za-z0-9_-]+$/.test(parts[2])) {
        sendJson(req, res, 400, { error: 'Bad library id' });
        return;
      }
      const file = path.join(LIBRARY_DIR, `${parts[2]}.json`);
      try {
        const raw = await fs.readFile(file, 'utf8');
        res.writeHead(200, {
          'Content-Type': 'application/json',
          ...corsHeaders(req),
        });
        res.end(raw);
      } catch {
        sendJson(req, res, 404, { error: 'Unknown library id' });
      }
      return;
    }

    // Ingest a finished solve produced elsewhere (the local PC runner).
    // Body: { spot: {...catalog metadata, incl. id}, result: <engine JSON> }.
    // Stored exactly like a job-produced library entry, plus
    // source: "local-runner", the spot metadata, and a content hash that
    // makes re-ingesting the identical solve a no-op ({status: "exists"}).
    if (req.method === 'POST' && url.pathname === '/api/library/ingest') {
      if (!(await requireAdmin(req, res))) return;
      try {
        const text = await readBodyWithLimit(req, INGEST_MAX_BYTES);
        let body;
        try {
          body = JSON.parse(text);
        } catch {
          throw new HttpError(400, 'Body must be valid JSON: { spot, result }.');
        }
        const spot = body && typeof body === 'object' ? body.spot : undefined;
        const result = body && typeof body === 'object' ? body.result : undefined;
        if (!spot || typeof spot !== 'object' || Array.isArray(spot)) {
          throw new HttpError(400, 'Body must carry a spot object (catalog-shaped metadata).');
        }
        if (typeof spot.id !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9_-]*$/.test(spot.id)) {
          throw new HttpError(400, 'spot.id must be a non-empty id string (letters, digits, - and _).');
        }
        if (!result || typeof result !== 'object' || Array.isArray(result)) {
          throw new HttpError(422, 'Body must carry a result object (the engine solve JSON).');
        }
        const nash = result?.exploitability?.nash_distance_pct;
        if (typeof result.board !== 'string' || typeof nash !== 'number' || typeof result.iterations !== 'number') {
          throw new HttpError(
            422,
            'result is not a recognisable engine solve (needs board, exploitability.nash_distance_pct and iterations).',
          );
        }
        const contentHash = createHash('sha256')
          .update(spot.id, 'utf8')
          .update('\n')
          .update(JSON.stringify(result), 'utf8')
          .digest('hex');
        await fs.mkdir(LIBRARY_DIR, { recursive: true });
        const metaPath = path.join(LIBRARY_DIR, `${spot.id}.meta.json`);
        let priorMeta = null;
        try {
          priorMeta = JSON.parse(await fs.readFile(metaPath, 'utf8'));
        } catch {
          priorMeta = null;
        }
        if (priorMeta && priorMeta.content_hash === contentHash) {
          sendJson(req, res, 200, {
            status: 'exists',
            id: spot.id,
            nash_distance_pct: nash,
            iterations: result.iterations,
          });
          return;
        }
        const kind = ['river', 'turn', 'flop'].includes(spot.kind)
          ? spot.kind
          : kindForBoard(result.board) ?? 'river';
        const meta = {
          id: spot.id,
          name: typeof spot.name === 'string' && spot.name.length > 0 ? spot.name : `Solve · ${result.board}`,
          kind,
          street: kind,
          board: result.board,
          oop_range_set: typeof spot.oop_range_set === 'string' ? spot.oop_range_set : null,
          ip_range_set: typeof spot.ip_range_set === 'string' ? spot.ip_range_set : null,
          nash_distance_pct: nash,
          iterations: result.iterations,
          finished_at: nowIso(),
          source: 'local-runner',
          spot,
          content_hash: contentHash,
        };
        await fs.writeFile(path.join(LIBRARY_DIR, `${spot.id}.json`), JSON.stringify(result));
        await fs.writeFile(metaPath, JSON.stringify(meta, null, 2));
        sendJson(req, res, priorMeta ? 200 : 201, {
          status: priorMeta ? 'updated' : 'created',
          id: spot.id,
          nash_distance_pct: nash,
          iterations: result.iterations,
        });
        return;
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
    }

    if (req.method === 'GET' && url.pathname === '/api/preflop/index') {
      await sendJsonFile(req, res, path.join(PREFLOP_DIR, 'index.json'));
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/preflop/class-table') {
      const file = path.join(PREFLOP_DIR, 'class-table.json');
      try {
        await fs.access(file);
      } catch {
        sendJson(req, res, 404, {
          error:
            'Class table not generated yet: data/preflop/class-table.json is written by the engine build-ranges tool on a host.',
        });
        return;
      }
      await sendJsonFile(req, res, file);
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'preflop' && parts[2] === 'sets' && parts[3]) {
      let entry;
      try {
        entry = await findPreflopSetEntry(parts[3]);
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(req, res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      if (!entry) {
        sendJson(req, res, 404, { error: `Unknown preflop range set id "${parts[3]}"` });
        return;
      }
      const file = preflopEntryPath(entry);
      if (!file) {
        sendJson(req, res, 500, { error: `Preflop index entry for "${parts[3]}" has an unsafe path` });
        return;
      }
      await sendJsonFile(req, res, file);
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/health') {
      sendJson(req, res, 200, {
        ok: true,
        engine_bin: ENGINE_BIN,
        data_dir: DATA_DIR,
        preflop_dir: PREFLOP_DIR,
        auth_enabled: AUTH_ENABLED,
      });
      return;
    }

    sendJson(req, res, 404, { error: 'Not found' });
  } catch (err) {
    sendJson(req, res, 500, { error: err instanceof Error ? err.message : 'Internal error' });
  }
});

