/** @type {Map<string, object>} */
const jobs = new Map();

// Internal job scheduler. Historically solves ran strictly one at a time
// (a promise chain); the catalog queue needs up to `concurrency` engine
// processes at once on the runner PC, so submissions go through a small
// pending list instead. The concurrency limit is 1 whenever the queue is
// disabled (the historical behaviour for direct POST /api/solves use),
// and the queue's configured concurrency when QUEUE_ENABLED=1 — direct
// submissions share the same pool, so the machine is never oversubscribed
// beyond the admin's setting.
/** @type {{job: object, spot: object}[]} */
const pendingJobs = [];
let activeJobCount = 0;

function jobConcurrencyLimit() {
  return QUEUE_ENABLED ? Math.max(1, queueState.concurrency) : 1;
}

function pumpJobs() {
  while (activeJobCount < jobConcurrencyLimit() && pendingJobs.length > 0) {
    const next = pendingJobs.shift();
    activeJobCount += 1;
    runJob(next.job, next.spot)
      .catch(() => undefined)
      .finally(() => {
        activeJobCount -= 1;
        pumpJobs();
      });
  }
}

/**
 * Create a job record for an engine spot and schedule it. Shared by
 * POST /api/solves and the catalog queue worker. `meta` may carry
 * { name, oop_range_set, ip_range_set, spot_id, range_expansion }.
 */
async function submitJob(spot, meta = {}) {
  const job = {
    id: randomUUID().slice(0, 8),
    status: 'queued',
    kind: kindForBoard(spot.board),
    board: spot.board,
    name: meta.name ?? `Custom solve · ${spot.board}`,
    oop_range_set: meta.oop_range_set ?? null,
    ip_range_set: meta.ip_range_set ?? null,
    spot_id: meta.spot_id ?? null,
    range_expansion: meta.range_expansion ?? null,
    created_at: nowIso(),
    finished_at: null,
    nash_distance_pct: null,
    iterations: null,
    error: null,
  };
  jobs.set(job.id, job);
  await writeJobFile(job);
  pendingJobs.push({ job, spot });
  pumpJobs();
  return job;
}

function nowIso() {
  return new Date().toISOString();
}

function boardCardCount(board) {
  if (typeof board !== 'string') return 0;
  return board.split(/[\s,]+/).filter((t) => t.trim().length > 0).length;
}

function kindForBoard(board) {
  const n = boardCardCount(board);
  if (n === 5) return 'river';
  if (n === 4) return 'turn';
  if (n === 3) return 'flop';
  return null;
}

async function writeJobFile(job) {
  const dir = path.join(JOBS_DIR, job.id);
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, 'job.json'), JSON.stringify(job, null, 2));
}

async function runJob(job, spot) {
  job.status = 'running';
  await writeJobFile(job);
  const dir = path.join(JOBS_DIR, job.id);
  const spotPath = path.join(dir, 'spot.json');
  const resultPath = path.join(dir, 'result.json');
  await fs.writeFile(spotPath, JSON.stringify(spot, null, 2));

  const binaryName =
    job.kind === 'flop' ? 'solve-flop' : job.kind === 'turn' ? 'solve-turn' : 'solve-river';
  const binary = path.join(ENGINE_BIN, binaryName);
  try {
    await fs.access(binary);
  } catch {
    job.status = 'error';
    job.error = `Engine binary not found at ${binary}. Build the engine (cargo build --release) or set ENGINE_BIN.`;
    job.finished_at = nowIso();
    await writeJobFile(job);
    return;
  }

  const code = await new Promise((resolve) => {
    const child = spawn(binary, [spotPath, resultPath], { stdio: ['ignore', 'pipe', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', (chunk) => {
      stderr += String(chunk);
    });
    const timer = setTimeout(() => {
      child.kill('SIGKILL');
    }, JOB_TIMEOUT_MS);
    child.on('error', () => {
      clearTimeout(timer);
      resolve(-1);
    });
    child.on('close', (exitCode) => {
      clearTimeout(timer);
      job.stderr_tail = stderr.slice(-2000);
      resolve(exitCode ?? -1);
    });
  });

  if (code !== 0) {
    job.status = 'error';
    job.error = `Engine exited with code ${code}. ${job.stderr_tail ?? ''}`.trim();
    job.finished_at = nowIso();
    await writeJobFile(job);
    return;
  }

  try {
    const raw = await fs.readFile(resultPath, 'utf8');
    const result = JSON.parse(raw);
    job.nash_distance_pct = result?.exploitability?.nash_distance_pct ?? null;
    job.iterations = result?.iterations ?? null;
    job.status = 'done';
    job.finished_at = nowIso();
    // Publish into the library.
    await fs.mkdir(LIBRARY_DIR, { recursive: true });
    await fs.writeFile(path.join(LIBRARY_DIR, `${job.id}.json`), raw);
    await fs.writeFile(
      path.join(LIBRARY_DIR, `${job.id}.meta.json`),
      JSON.stringify(
        {
          id: job.id,
          name: job.name,
          kind: job.kind,
          street: job.kind,
          board: job.board,
          oop_range_set: job.oop_range_set ?? null,
          ip_range_set: job.ip_range_set ?? null,
          spot_id: job.spot_id ?? null,
          range_expansion: job.range_expansion ?? null,
          nash_distance_pct: job.nash_distance_pct,
          iterations: job.iterations,
          finished_at: job.finished_at,
        },
        null,
        2,
      ),
    );
  } catch (err) {
    job.status = 'error';
    job.error = `Could not read engine result: ${err instanceof Error ? err.message : String(err)}`;
    job.finished_at = nowIso();
  }
  await writeJobFile(job);
}

function publicJob(job) {
  const { stderr_tail, ...rest } = job;
  return rest;
}

async function listLibrary() {
  await fs.mkdir(LIBRARY_DIR, { recursive: true });
  const files = (await fs.readdir(LIBRARY_DIR)).filter(
    (f) => f.endsWith('.json') && !f.endsWith('.meta.json'),
  );
  const items = [];
  for (const file of files) {
    const id = file.replace(/\.json$/, '');
    const full = path.join(LIBRARY_DIR, file);
    try {
      const raw = await fs.readFile(full, 'utf8');
      const result = JSON.parse(raw);
      let meta = {};
      try {
        meta = JSON.parse(await fs.readFile(path.join(LIBRARY_DIR, `${id}.meta.json`), 'utf8'));
      } catch {
        meta = {};
      }
      const stat = await fs.stat(full);
      items.push({
        id,
        name: meta.name ?? `Solve · ${result.board ?? id}`,
        kind: meta.kind ?? meta.street ?? kindForBoard(result.board) ?? 'river',
        board: result.board ?? '',
        oop_range_set: meta.oop_range_set ?? null,
        ip_range_set: meta.ip_range_set ?? null,
        spot_id: meta.spot_id ?? meta.id ?? null,
        nash_distance_pct:
          result?.exploitability?.nash_distance_pct ?? meta.nash_distance_pct ?? null,
        iterations: result?.iterations ?? meta.iterations ?? null,
        finished_at: meta.finished_at ?? null,
        size_bytes: stat.size,
      });
    } catch {
      // Skip unreadable entries rather than failing the whole list.
    }
  }
  items.sort((a, b) => String(b.finished_at ?? '').localeCompare(String(a.finished_at ?? '')));
  return items;
}

