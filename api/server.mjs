// Thin job service for PLO GTO Study — Node standard library only.
//
//   POST /api/solves            spot JSON -> job record (queued) [admin]
//   GET  /api/solves/:id        job status
//   GET  /api/solves/:id/result finished solve JSON (engine output)
//   GET  /api/jobs              all job records this process knows
//   GET  /api/library           finished solves in the data dir
//   GET  /api/library/:id       one library solve JSON
//   POST /api/library/ingest    finished solve + spot metadata -> library [admin]
//   GET  /api/catalog           spot catalog + library/queue status per spot
//   GET  /api/queue             queue items + concurrency + paused
//   POST /api/queue             enqueue catalog spots [admin]
//   POST /api/queue/control     pause/resume/remove/set_concurrency [admin]
//   GET  /api/preflop/index     preflop range-set index (data/preflop/index.json)
//   GET  /api/preflop/sets/:id  one preflop range set (id must be in the index)
//   GET  /api/quiz/progress     SRS item states + per-topic accuracy [admin]
//   POST /api/quiz/answer       record one graded quiz answer [admin]
//   GET  /api/preflop/class-table  per-class feature/equity table
//                               (data/preflop/class-table.json, generated by
//                               the engine's build-ranges tool)
//   GET|POST /api/heuristics    personal heuristics log [admin] (study.mjs)
//   PUT|DELETE /api/heuristics/:id                    [admin] (study.mjs)
//   POST /api/study/review-events  Quick Review outcomes [admin] (study.mjs)
//   GET  /api/study/progress    review-outcome summary [admin] (study.mjs)
//   POST /api/multiway/equity   exact or seeded MC multiway equity (hero hand
//                               or range vs 1..4 opponent ranges on 3/4/5-card board)
//   POST /api/auth/login        password -> admin session cookie
//   POST /api/auth/google       Google ID token -> admin session cookie
//                               (allowlisted emails only, see google-auth.mjs)
//   GET  /api/auth/config       public sign-in config ({ google_client_id })
//   POST /api/auth/logout       clear the admin session
//   GET  /api/auth/me           { admin: true } (+ email/provider when the
//                               session carries them) or 401
//
// Jobs run one at a time (solves are CPU-heavy). The service writes the
// spot JSON to DATA_DIR/jobs/<id>/spot.json, invokes the engine binary
// (solve-river for 5-card boards, solve-turn for 4-card boards, solve-flop
// for 3-card boards) from ENGINE_BIN, and on success copies the result
// into DATA_DIR/library/.
//
// A solve submission may name a preflop range set per side
// (`oop_range_set` / `ip_range_set`, a set id from the preflop index) in
// place of the raw `oop_range` / `ip_range` arrays. The server expands the
// set into per-combo engine range entries (ranges-expand.mjs) and records
// the set ids on the job. Per-side `*_range_cap` / `*_range_mode` /
// `*_range_seed` / `*_range_action` / `*_range_base_set` fields switch a
// side to the capped expansion (top/sample, optional product base).
//
// A submission may also carry `locks` (nodelocking): an array of
// { history, player, frequencies } specs the engine holds fixed during
// the solve. The field is shape-validated here (400 on malformed specs)
// and forwarded verbatim in the engine spot; semantic validation (node
// exists, player to act, vector length) is the engine's, and a failure
// there ends the job in `error` with the engine's message. Jobs and
// library entries for locked solves record `locked: true` — a locked
// solve is NOT an equilibrium and must be badged LOCKED, never CERTIFIED.
//
// LOCAL RUNNER (RUN-1): with QUEUE_ENABLED=1 the server also works the
// persistent catalog queue (DATA_DIR/queue.json): queued spots are
// translated to engine spots, solved through the same job path, and
// uploaded to the central library (DATA_DIR/runner-config.json, written
// by runner-login.mjs). See README.md "Local runner queue".
//
// AUTH: every WRITE endpoint ([admin] above) requires an admin session
// when ADMIN_PASSWORD_HASH is set (see auth.mjs and README.md). When it
// is NOT set, auth is disabled and the writes are open — the server logs
// a loud warning at startup; that mode is for local development only.

