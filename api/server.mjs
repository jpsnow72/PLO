const VALID_CARD_RANKS = new Set(['2', '3', '4', '5', '6', '7', '8', '9', 'T', 'J', 'Q', 'K', 'A']);
const VALID_CARD_SUITS = new Set(['s', 'h', 'd', 'c']);
const MAX_MULTIWAY_OPPONENTS = 4;

/**
 * Parse a string or array of card tokens into canonical two-char card labels
 * ("As", "Td", ...). Supports both whitespace/comma-separated ("As Ks Qs")
 * and packed ("AsKsQs") card strings. Rejects invalid tokens and duplicates
 * within the same list.
 */
function parseCardTokens(input, fieldLabel) {
  let rawText = '';
  if (typeof input === 'string') {
    rawText = input.trim();
  } else if (Array.isArray(input)) {
    if (input.some((item) => typeof item !== 'string')) {
      throw new HttpError(400, `${fieldLabel} array elements must be card strings.`);
    }
    rawText = input.join(' ').trim();
  } else {
    throw new HttpError(400, `${fieldLabel} must be a card string or array of card strings.`);
  }

  if (rawText.length === 0) return [];

  const cleaned = rawText.replace(/,/g, ' ');
  const cards = [];
  const seen = new Set();
  let i = 0;
  while (i < cleaned.length) {
    while (i < cleaned.length && /\s/.test(cleaned[i])) i += 1;
    if (i >= cleaned.length) break;
    if (i + 1 >= cleaned.length) {
      throw new HttpError(400, `${fieldLabel}: unexpected card token in "${rawText}".`);
    }
    const r = cleaned[i].toUpperCase();
    const s = cleaned[i + 1].toLowerCase();
    if (!VALID_CARD_RANKS.has(r) || !VALID_CARD_SUITS.has(s)) {
      throw new HttpError(
        400,
        `${fieldLabel}: invalid card "${cleaned.slice(i, i + 2)}" in "${rawText}".`,
      );
    }
    // After a 2-char card, the next char must be whitespace or another valid rank (packed format)
    const label = `${r}${s}`;
    if (seen.has(label)) {
      throw new HttpError(400, `${fieldLabel} contains duplicate card "${label}".`);
    }
    seen.add(label);
    cards.push(label);
    i += 2;
  }
  return cards;
}

function isRandomPreset(val) {
  if (typeof val !== 'string') return false;
  const t = val.trim().toLowerCase();
  return t === 'random' || t === 'all' || t === 'any' || t === '*' || t === '100%';
}

/**
 * Parse a single combo specification ("Ts 9s 3c 4c" or "Ts 9s 3c 4c:0.5").
 * Returns { cards: string[4], combo: string, weight: number }.
 */
function parseWeightedComboEntry(specText, fieldLabel) {
  const trimmed = specText.trim();
  const colonIdx = trimmed.lastIndexOf(':');
  let handPart = trimmed;
  let weight = 1;
  if (colonIdx >= 0) {
    const wText = trimmed.slice(colonIdx + 1).trim();
    const w = Number(wText);
    if (wText.length === 0 || !Number.isFinite(w) || w <= 0) {
      throw new HttpError(400, `${fieldLabel}: invalid combo weight in "${trimmed}".`);
    }
    weight = w;
    handPart = trimmed.slice(0, colonIdx).trim();
  }
  const cards = parseCardTokens(handPart, fieldLabel);
  if (cards.length !== 4) {
    throw new HttpError(
      400,
      `${fieldLabel}: PLO combo must have 4 distinct cards, got ${cards.length} in "${trimmed}".`,
    );
  }
  return {
    cards,
    combo: cards.join(' '),
    weight,
  };
}

/**
 * Parse a range input (Solver textarea string, array of strings/objects/pairs,
 * object map, "random" preset, or { range, range_set, label }) into
 * { isRandom: boolean, entries: {cards: string[], combo: string, weight: number}[], label: string|null }.
 */
async function parseMultiwayRangeInput(rawInput, fieldLabel) {
  let label = null;
  let target = rawInput;

  if (rawInput && typeof rawInput === 'object' && !Array.isArray(rawInput)) {
    if (typeof rawInput.label === 'string' && rawInput.label.trim().length > 0) {
      label = rawInput.label.trim();
    } else if (typeof rawInput.name === 'string' && rawInput.name.trim().length > 0) {
      label = rawInput.name.trim();
    }
    if (typeof rawInput.range_set === 'string' && rawInput.range_set.trim().length > 0) {
      const expanded = await expandRangeSet(rawInput.range_set.trim());
      target = expanded.range;
    } else if ('range' in rawInput) {
      target = rawInput.range;
    }
  }

  if (typeof target === 'string') {
    if (isRandomPreset(target)) {
      return { isRandom: true, entries: [], label };
    }
    const parts = target
      .split(/[\n,;]+/)
      .map((p) => p.trim())
      .filter((p) => p.length > 0);
    if (parts.length === 0) {
      throw new HttpError(400, `${fieldLabel} cannot be empty.`);
    }
    const entries = parts.map((part) => parseWeightedComboEntry(part, fieldLabel));
    return { isRandom: false, entries, label };
  }

  if (Array.isArray(target)) {
    if (target.length === 0) {
      throw new HttpError(400, `${fieldLabel} cannot be an empty array.`);
    }
    const entries = [];
    for (const item of target) {
      if (typeof item === 'string') {
        entries.push(parseWeightedComboEntry(item, fieldLabel));
      } else if (Array.isArray(item) && item.length === 2 && typeof item[0] === 'string') {
        const w = Number(item[1]);
        if (!Number.isFinite(w) || w <= 0) {
          throw new HttpError(400, `${fieldLabel}: invalid combo weight "${item[1]}".`);
        }
        const parsed = parseWeightedComboEntry(item[0], fieldLabel);
        entries.push({ ...parsed, weight: w });
      } else if (item && typeof item === 'object' && !Array.isArray(item)) {
        const comboStr = item.combo ?? item.hand;
        if (typeof comboStr !== 'string') {
          throw new HttpError(400, `${fieldLabel}: range object must have a "combo" string.`);
        }
        const w = item.weight === undefined ? 1 : Number(item.weight);
        if (!Number.isFinite(w) || w <= 0) {
          throw new HttpError(400, `${fieldLabel}: invalid combo weight "${item.weight}".`);
        }
        const parsed = parseWeightedComboEntry(comboStr, fieldLabel);
        entries.push({ ...parsed, weight: w });
      } else {
        throw new HttpError(400, `${fieldLabel}: unsupported range element format.`);
      }
    }
    return { isRandom: false, entries, label };
  }

  if (target && typeof target === 'object') {
    const keys = Object.keys(target);
    if (keys.length === 0) {
      throw new HttpError(400, `${fieldLabel} cannot be an empty object.`);
    }
    const entries = [];
    for (const [k, v] of Object.entries(target)) {
      const w = Number(v);
      if (!Number.isFinite(w) || w <= 0) {
        throw new HttpError(400, `${fieldLabel}: invalid weight for "${k}".`);
      }
      const parsed = parseWeightedComboEntry(k, fieldLabel);
      entries.push({ ...parsed, weight: w });
    }
    return { isRandom: false, entries, label };
  }

  throw new HttpError(400, `${fieldLabel} must be a range string, array, or "random".`);
}

/**
 * Validate a POST /api/multiway/equity request body and build the normalized
 * JSON payload for the `multiway-equity` engine binary.
 */
async function buildMultiwayEnginePayload(body) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    throw new HttpError(400, 'Request body must be a JSON object.');
  }

  if (body.board === undefined || body.board === null) {
    throw new HttpError(400, 'Missing required field "board" (3, 4, or 5 cards).');
  }
  const boardCards = parseCardTokens(body.board, 'Board');
  if (![3, 4, 5].includes(boardCards.length)) {
    throw new HttpError(
      400,
      `Board must have 3, 4, or 5 distinct cards, got ${boardCards.length}.`,
    );
  }
  const boardSet = new Set(boardCards);

  const deadInput = body.dead_cards ?? body.dead ?? null;
  const deadCards = deadInput !== null ? parseCardTokens(deadInput, 'Dead cards') : [];

  // Hero: hero_hand, hero_range, hero_range_set, or hero
  let heroKind = null;
  let heroHandCards = null;
  let heroRangeParsed = null;

  if (body.hero_hand !== undefined && body.hero_hand !== null) {
    heroHandCards = parseCardTokens(body.hero_hand, 'Hero hand');
    if (heroHandCards.length !== 4) {
      throw new HttpError(
        400,
        `Hero hand must have 4 distinct cards, got ${heroHandCards.length}.`,
      );
    }
    heroKind = 'hand';
  } else if (typeof body.hero_range_set === 'string' && body.hero_range_set.trim().length > 0) {
    heroRangeParsed = await parseMultiwayRangeInput(
      { range_set: body.hero_range_set.trim() },
      'Hero range',
    );
    heroKind = 'range';
  } else if (body.hero_range !== undefined && body.hero_range !== null) {
    heroRangeParsed = await parseMultiwayRangeInput(body.hero_range, 'Hero range');
    heroKind = 'range';
  } else if (body.hero !== undefined && body.hero !== null) {
    if (
      typeof body.hero === 'string' &&
      !isRandomPreset(body.hero) &&
      !body.hero.includes(',') &&
      !body.hero.includes('\n') &&
      !body.hero.includes(';') &&
      !body.hero.includes(':')
    ) {
      heroHandCards = parseCardTokens(body.hero, 'Hero hand');
      if (heroHandCards.length !== 4) {
        throw new HttpError(
          400,
          `Hero hand must have 4 distinct cards, got ${heroHandCards.length}.`,
        );
      }
      heroKind = 'hand';
    } else {
      heroRangeParsed = await parseMultiwayRangeInput(body.hero, 'Hero range');
      heroKind = 'range';
    }
  } else {
    throw new HttpError(
      400,
      'Missing required hero field ("hero", "hero_hand", or "hero_range").',
    );
  }

  // Fixed card collision check (board + hero_hand + single-hand opponents)
  const fixedUsedCards = new Map();
  for (const c of boardCards) {
    fixedUsedCards.set(c, 'board');
  }
  for (const c of deadCards) {
    if (!fixedUsedCards.has(c)) {
      fixedUsedCards.set(c, 'dead_cards');
    }
  }

  if (heroKind === 'hand') {
    for (const c of heroHandCards) {
      const existing = fixedUsedCards.get(c);
      if (existing) {
        throw new HttpError(400, `Duplicate card "${c}" between ${existing} and hero hand.`);
      }
    }
    for (const c of heroHandCards) {
      fixedUsedCards.set(c, 'hero hand');
    }
  } else if (heroRangeParsed && !heroRangeParsed.isRandom) {
    const unblockedHero = heroRangeParsed.entries.filter((e) =>
      e.cards.every((c) => !fixedUsedCards.has(c)),
    );
    if (unblockedHero.length === 0) {
      throw new HttpError(400, 'All combos in Hero range collide with board/dead cards.');
    }
  }

  const rawOpponents = body.opponents ?? body.opponent_ranges;
  if (!Array.isArray(rawOpponents)) {
    throw new HttpError(400, 'Missing required array field "opponents" (1..4 opponent ranges).');
  }
  if (rawOpponents.length < 1 || rawOpponents.length > MAX_MULTIWAY_OPPONENTS) {
    throw new HttpError(
      400,
      `Multiway equity requires between 1 and ${MAX_MULTIWAY_OPPONENTS} opponents, got ${rawOpponents.length}.`,
    );
  }

  const parsedOpponents = [];
  for (let i = 0; i < rawOpponents.length; i += 1) {
    const oppLabel = `Opponent ${i + 1}`;
    const parsed = await parseMultiwayRangeInput(rawOpponents[i], oppLabel);
    if (!parsed.isRandom) {
      if (parsed.entries.length === 1) {
        for (const c of parsed.entries[0].cards) {
          const existing = fixedUsedCards.get(c);
          if (existing) {
            throw new HttpError(400, `Duplicate card "${c}" between ${existing} and ${oppLabel}.`);
          }
        }
        for (const c of parsed.entries[0].cards) {
          fixedUsedCards.set(c, oppLabel);
        }
      } else {
        const unblocked = parsed.entries.filter((e) =>
          e.cards.every((c) => !fixedUsedCards.has(c)),
        );
        if (unblocked.length === 0) {
          throw new HttpError(400, `All combos in ${oppLabel} range collide with board/dead cards.`);
        }
      }
    }
    parsedOpponents.push({
      label: parsed.label ?? oppLabel,
      range: parsed.isRandom
        ? 'random'
        : parsed.entries.map((e) => `${e.combo}:${formatWeight(e.weight)}`),
    });
  }

  const payload = {
    board: boardCards.join(' '),
    opponents: parsedOpponents,
  };
  if (deadCards.length > 0) {
    payload.dead_cards = deadCards.join(' ');
  }
  if (heroKind === 'hand') {
    payload.hero_hand = heroHandCards.join(' ');
  } else if (heroRangeParsed.isRandom) {
    payload.hero_range = 'random';
  } else {
    payload.hero_range = heroRangeParsed.entries.map(
      (e) => `${e.combo}:${formatWeight(e.weight)}`,
    );
  }

  if (body.mode !== undefined && body.mode !== null) {
    if (
      typeof body.mode !== 'string' ||
      !['auto', 'exact', 'mc', 'monte_carlo'].includes(body.mode.toLowerCase())
    ) {
      throw new HttpError(400, 'mode must be "auto", "exact", or "monte_carlo".');
    }
    payload.mode = body.mode.toLowerCase();
  }
  const samples = body.samples ?? body.mc_samples;
  if (samples !== undefined && samples !== null) {
    if (!Number.isInteger(samples) || samples < 1 || samples > 5_000_000) {
      throw new HttpError(400, 'samples must be an integer between 1 and 5,000,000.');
    }
    payload.samples = samples;
  }
  if (body.seed !== undefined && body.seed !== null) {
    if (!Number.isInteger(body.seed) || body.seed < 0) {
      throw new HttpError(400, 'seed must be a non-negative integer.');
    }
    payload.seed = body.seed;
  }

  return payload;
}

/**
 * Invoke the `multiway-equity` binary with a JSON request on stdin and a
 * wall-clock timeout, returning the parsed JSON response.
 */
async function runMultiwayEquityBinary(payload) {
  const exeName = process.platform === 'win32' ? 'multiway-equity.exe' : 'multiway-equity';
  let binary = path.join(ENGINE_BIN, exeName);
  try {
    await fs.access(binary);
  } catch {
    const fallback = path.join(ENGINE_BIN, 'multiway-equity');
    try {
      await fs.access(fallback);
      binary = fallback;
    } catch {
      throw new HttpError(
        503,
        `Engine binary not found at ${binary}. Build the engine (cargo build --release) or set ENGINE_BIN.`,
      );
    }
  }

  const inputJson = JSON.stringify(payload);
  const outcome = await new Promise((resolve) => {
    const child = spawn(binary, [], { stdio: ['pipe', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    let timedOut = false;

    child.stdout.on('data', (chunk) => {
      stdout += String(chunk);
    });
    child.stderr.on('data', (chunk) => {
      stderr += String(chunk);
    });
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill('SIGKILL');
    }, MULTIWAY_TIMEOUT_MS);
    child.on('error', (err) => {
      clearTimeout(timer);
      resolve({ code: -1, stdout, stderr: err.message, timedOut });
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      resolve({ code: code ?? -1, stdout, stderr, timedOut });
    });
    child.stdin.on('error', () => undefined);
    child.stdin.end(inputJson);
  });

  if (outcome.timedOut) {
    throw new HttpError(
      504,
      `Multiway equity calculation timed out after ${MULTIWAY_TIMEOUT_MS} ms.`,
    );
  }
  if (outcome.code !== 0) {
    const detail = outcome.stderr.trim() || `Engine exited with code ${outcome.code}`;
    throw new HttpError(422, detail);
  }
  try {
    return JSON.parse(outcome.stdout);
  } catch {
    throw new HttpError(500, 'Engine returned malformed JSON.');
  }
}


// ---------------------------------------------------------------------------
// Catalog + persistent solve queue (RUN-1)
//
// The catalog (data/library/spot-catalog.json) lists the ~300 planned
// library spots. The queue is the runner's work list: Justin picks spots,
// they solve consecutively (up to `concurrency` at once) through the same
// internal job path as POST /api/solves, and each finished solve — which
// by then exists in the LOCAL library — is uploaded to the central
// library (uploader.mjs).
//
// CRASH CONTRACT: queue state persists to DATA_DIR/queue.json (atomic
// temp + rename) on EVERY transition. An item is marked done only after
// its job finished AND the job's library entry exists on disk. On server
// start, items left "running" revert to "queued" (their engine process
// died with the server; partial results are never ingested, and the job
// registry is in-memory so the interrupted job is simply gone). "done"
// items stay done. Uploads are idempotent (central ingest dedupes by
// content hash) and retry on start + on a timer.
// ---------------------------------------------------------------------------

/** @type {object | null} */
let catalogCache = null;

async function loadCatalog() {
  if (catalogCache) return catalogCache;
  let parsed;
  try {
    parsed = JSON.parse(await fs.readFile(CATALOG_PATH, 'utf8'));
  } catch {
    throw new HttpError(500, `Spot catalog not readable at ${CATALOG_PATH}`);
  }
  if (!parsed || !Array.isArray(parsed.entries)) {
    throw new HttpError(500, 'Spot catalog is malformed (no entries array)');
  }
  catalogCache = parsed;
  return parsed;
}

async function findCatalogEntry(spotId) {
  const catalog = await loadCatalog();
  return catalog.entries.find((entry) => entry && entry.id === spotId) ?? null;
}

// --- Queue state -----------------------------------------------------------

const QUEUE_PATH = path.join(DATA_DIR, 'queue.json');

/** @type {{items: object[], concurrency: number, paused: boolean}} */
const queueState = { items: [], concurrency: 1, paused: false };
let queueSaveChain = Promise.resolve();

/** Persist queue state atomically; saves are serialised through a chain. */
function saveQueue() {
  const snapshot = JSON.stringify(
    {
      items: queueState.items,
      concurrency: queueState.concurrency,
      paused: queueState.paused,
    },
    null,
    2,
  );
  queueSaveChain = queueSaveChain
    .then(async () => {
      await fs.mkdir(DATA_DIR, { recursive: true });
      const tmp = `${QUEUE_PATH}.tmp-${process.pid}`;
      await fs.writeFile(tmp, snapshot);
      await fs.rename(tmp, QUEUE_PATH);
    })
    .catch((err) => {
      console.error(`queue: could not persist state: ${err instanceof Error ? err.message : err}`);
    });
  return queueSaveChain;
}

/**
 * Load persisted queue state at startup and apply the crash contract:
 * "running" items revert to "queued"; everything else is kept as-is.
 * A missing/corrupt file starts an empty queue (corruption is logged —
 * the queue is a work list, not the library; done solves also exist as
 * library entries and re-adding a spot is reported, not duplicated).
 */
async function loadQueue() {
  let parsed = null;
  try {
    parsed = JSON.parse(await fs.readFile(QUEUE_PATH, 'utf8'));
  } catch {
    parsed = null;
  }
  if (parsed && Array.isArray(parsed.items)) {
    queueState.items = parsed.items.filter(
      (item) => item && typeof item.spot_id === 'string' && typeof item.state === 'string',
    );
    if (Number.isInteger(parsed.concurrency)) {
      queueState.concurrency = Math.min(8, Math.max(1, parsed.concurrency));
    }
    queueState.paused = parsed.paused === true;
  }
  let recovered = 0;
  for (const item of queueState.items) {
    if (item.state === 'running') {
      item.state = 'queued';
      item.job_id = null;
      item.started_at = null;
      item.error = null;
      recovered += 1;
    }
  }
  if (recovered > 0) {
    console.log(`queue: recovered ${recovered} interrupted item(s) back to queued`);
    await saveQueue();
  }
  return queueState;
}

function queueItemFor(spotId) {
  return queueState.items.find((item) => item.spot_id === spotId) ?? null;
}

// --- Catalog -> engine spot translation ------------------------------------

/**
 * The RFI base set for a 3-bet continuation side. The v1.1 continuation
 * sets (context vs_three_bet) store frequencies CONDITIONAL on opening,
 * so a combo's postflop weight is base-RFI-freq x conditional-freq (the
 * catalog generator's coverage_product convention). The catalog's three
 * pairings, as generated:
 *   constructed-v1.1-6max-btn-vs-bb-3bet -> constructed-v1-6max-btn-rfi
 *   constructed-v1.1-6max-btn-vs-sb-3bet -> constructed-v1-6max-btn-rfi
 *   constructed-v1.1-6max-co-vs-btn-3bet -> constructed-v1-6max-co-rfi
 * derived generically: same table size, the continuation set's own
 * position, its `rfi` set, action `raise`.
 */
async function continuationBase(setId) {
  const doc = await rangeExpander.loadSet(setId);
  if (doc.context !== 'vs_three_bet') return null;
  const position = String(doc.position ?? '').toLowerCase();
  const baseSetId = `constructed-v1-${doc.table_size}-${position}-rfi`;
  return { baseSetId, baseAction: 'raise' };
}

/** Deterministic per-spot sampling seed: FNV-1a of the spot id (+ salt). */
function spotSeed(spotId) {
  return fnv1a32(QUEUE_RANGE_SEED ? `${QUEUE_RANGE_SEED}:${spotId}` : spotId);
}

/** Queue iteration budget: smoke override wins over the generous default. */
function queueMaxIterations() {
  return QUEUE_SMOKE_MAX_ITERATIONS ?? QUEUE_MAX_ITERATIONS;
}

/**
 * Translate one catalog entry into an engine spot + job metadata.
 *
 * Mapping (see RUN1-NOTES.md for the table):
 * - board / pot / stacks come straight from the entry (its pot_chips /
 *   stacks_chips are already the root state after its declared `line`).
 * - Ranges: expandRangeSetCapped per side with the entry's set + action +
 *   cap_per_side; continuation sides get their RFI product base; mode
 *   from QUEUE_RANGE_MODE; seed = spotSeed(entry.id).
 * - Sizes: the entry's size_menu carries per-street menus; each street's
 *   menu is written to the engine's `<street>_bet_sizes` /
 *   `<street>_raise_sizes` / `<street>_max_raises` (= 2) /
 *   `<street>_include_all_in` fields, and the ROOT street's menu also to
 *   the generic bet_sizes / raise_sizes / max_raises defaults the
 *   per-street parsers fall back to.
 * - Tier: balanced -> target 0.3%, precise -> target 0.1%.
 */
async function translateCatalogEntry(entry) {
  if (entry.status !== 'ready') {
    throw new HttpError(
      422,
      `Catalog spot "${entry.id}" is not ready (status "${entry.status}"` +
        (entry.status_reason ? `: ${entry.status_reason}` : '') +
        ')',
    );
  }
  const mode = QUEUE_RANGE_MODE;
  const expansions = {};
  const spot = {
    board: entry.board,
    pot: entry.pot_chips,
    stacks: entry.stacks_chips,
    max_iterations: queueMaxIterations(),
    target_exploitability_pct: entry.tier === 'precise' ? 0.1 : 0.3,
  };
  for (const side of ['oop', 'ip']) {
    const setId = entry[`${side}_set`];
    const action = entry[`range_action_${side}`];
    const base = await continuationBase(setId);
    const expanded = await expandRangeSetCapped({
      setId,
      action,
      cap: entry.cap_per_side,
      mode,
      seed: spotSeed(entry.id),
      baseSetId: base?.baseSetId ?? null,
      baseAction: base?.baseAction ?? 'raise',
    });
    spot[`${side}_range`] = expanded.range;
    expansions[side] = {
      set: setId,
      action: expanded.action,
      cap: entry.cap_per_side,
      mode: expanded.mode,
      seed: expanded.seed,
      kept_combos: expanded.kept_combos,
      total_combos: expanded.total_combos,
      coverage_pct: expanded.coverage_pct,
      base_set: expanded.base_set,
      base_action: expanded.base_action,
    };
  }
  const menu = entry.size_menu ?? {};
  for (const street of ['flop', 'turn', 'river']) {
    const streetMenu = menu[street];
    if (!streetMenu) continue;
    spot[`${street}_bet_sizes`] = streetMenu.bet_sizes;
    spot[`${street}_raise_sizes`] = streetMenu.raise_sizes;
    spot[`${street}_max_raises`] = 2;
    spot[`${street}_include_all_in`] = streetMenu.include_all_in !== false;
  }
  const rootMenu = menu[entry.street];
  if (rootMenu) {
    spot.bet_sizes = rootMenu.bet_sizes;
    spot.raise_sizes = rootMenu.raise_sizes;
    spot.max_raises = 2;
    spot.include_all_in = rootMenu.include_all_in !== false;
  }
  return {
    spot,
    meta: {
      name: `Catalog · ${entry.id}`,
      oop_range_set: entry.oop_set,
      ip_range_set: entry.ip_set,
      spot_id: entry.id,
      range_expansion: expansions,
    },
  };
}

// --- Upload -----------------------------------------------------------------

/**
 * Attempt to upload one done item's result to the central library and
 * record the outcome on the item. Never throws. Without a runner-config
 * the item is "skipped" (offline mode is a first-class state).
 */
async function attemptItemUpload(item) {
  const config = await loadRunnerConfig(DATA_DIR);
  if (!config) {
    if (item.upload_status !== 'skipped') {
      item.upload_status = 'skipped';
      item.upload_error = null;
      await saveQueue();
    }
    return;
  }
  const entry = await findCatalogEntry(item.spot_id).catch(() => null);
  if (!entry) {
    item.upload_status = 'failed';
    item.upload_error = 'Spot no longer present in the catalog; cannot build the ingest payload.';
    await saveQueue();
    return;
  }
  let result;
  try {
    result = JSON.parse(
      await fs.readFile(path.join(JOBS_DIR, item.job_id, 'result.json'), 'utf8'),
    );
  } catch {
    item.upload_status = 'failed';
    item.upload_error = 'Job result file is missing locally; cannot upload.';
    await saveQueue();
    return;
  }
  const outcome = await attemptUpload({ config, spot: entry, result });
  if (outcome.ok) {
    item.upload_status = 'uploaded';
    item.upload_error = null;
    item.uploaded_at = nowIso();
    item.upload_detail = outcome.status ?? null;
  } else {
    item.upload_status = 'failed';
    item.upload_error = outcome.error;
  }
  await saveQueue();
}

/** Retry uploads for done items that are not yet uploaded. */
async function retryPendingUploads() {
  for (const item of queueState.items) {
    if (item.state === 'done' && item.upload_status !== 'uploaded') {
      await attemptItemUpload(item);
    }
  }
}

// --- Worker -------------------------------------------------------------------

let queueTickRunning = false;

/**
 * One worker pass: settle running items whose jobs have finished, then
 * start queued items up to the concurrency limit. Runs on a 1s timer
 * when QUEUE_ENABLED=1 (and is kicked by queue mutations).
 */
async function queueTick() {
  if (queueTickRunning) return;
  queueTickRunning = true;
  try {
    // Settle: a queue item is done ONLY when its job is done AND the
    // job's library entry exists (runJob writes it before returning).
    for (const item of queueState.items) {
      if (item.state !== 'running' || !item.job_id) continue;
      const job = jobs.get(item.job_id);
      if (!job) {
        // The job registry is in-memory; a missing job here means the
        // process restarted mid-solve (loadQueue already reverts those)
        // or the job vanished — treat as interrupted, never as done.
        item.state = 'queued';
        item.job_id = null;
        item.started_at = null;
        await saveQueue();
        continue;
      }
      if (job.status === 'done') {
        let libraryExists = false;
        try {
          await fs.access(path.join(LIBRARY_DIR, `${job.id}.json`));
          libraryExists = true;
        } catch {
          libraryExists = false;
        }
        if (!libraryExists) {
          item.state = 'failed';
          item.error = 'Job reported done but its library entry is missing; refusing to mark done.';
          item.finished_at = nowIso();
          await saveQueue();
          continue;
        }
        item.state = 'done';
        item.finished_at = nowIso();
        item.nash_distance_pct = job.nash_distance_pct;
        item.iterations = job.iterations;
        item.error = null;
        if (item.upload_status === 'uploaded') item.upload_status = 'pending';
        await saveQueue();
        await attemptItemUpload(item);
      } else if (job.status === 'error') {
        item.state = 'failed';
        item.error = job.error ?? 'Engine job failed';
        item.finished_at = nowIso();
        await saveQueue();
      }
    }
    // Start: fill free slots from the front of the queue.
    if (!queueState.paused) {
      let running = queueState.items.filter((item) => item.state === 'running').length;
      for (const item of queueState.items) {
        if (running >= queueState.concurrency) break;
        if (item.state !== 'queued') continue;
        const entry = await findCatalogEntry(item.spot_id);
        if (!entry) {
          item.state = 'failed';
          item.error = 'Spot not found in the catalog.';
          item.finished_at = nowIso();
          await saveQueue();
          continue;
        }
        try {
          const { spot, meta } = await translateCatalogEntry(entry);
          const job = await submitJob(spot, meta);
          item.state = 'running';
          item.job_id = job.id;
          item.started_at = nowIso();
          item.finished_at = null;
          item.error = null;
          item.upload_status = 'pending';
          running += 1;
          await saveQueue();
        } catch (err) {
          item.state = 'failed';
          item.error = err instanceof Error ? err.message : String(err);
          item.finished_at = nowIso();
          await saveQueue();
        }
      }
    }
  } finally {
    queueTickRunning = false;
  }
}
/**
 * CORS headers for a response. Default: the historical wildcard (fine for
 * reads and same-origin use). When ALLOWED_ORIGIN is configured and the
 * request's Origin matches it exactly, echo that origin and allow
 * credentials, so the hosted UI can send the admin session cookie
 * cross-origin. See README.md ("Admin auth, CORS and cookies") for the
 * limits of that arrangement.
 */
function corsHeaders(req) {
  const origin = req?.headers?.origin;
  if (ALLOWED_ORIGIN && typeof origin === 'string' && origin === ALLOWED_ORIGIN) {
    return {
      'Access-Control-Allow-Origin': origin,
      'Access-Control-Allow-Credentials': 'true',
      Vary: 'Origin',
    };
  }
  return { 'Access-Control-Allow-Origin': '*' };
}

/** Serve a JSON file verbatim with a JSON content type. */
async function sendJsonFile(req, res, file) {
  let raw;
  try {
    raw = await fs.readFile(file, 'utf8');
  } catch {
    sendJson(req, res, 404, { error: `Not found: ${path.basename(file)}` });
    return;
  }
  res.writeHead(200, {
    'Content-Type': 'application/json',
    ...corsHeaders(req),
  });
  res.end(raw);
}

