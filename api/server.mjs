// Thin job service for PLO GTO Study — Node standard library only.
//
//   POST /api/solves            spot JSON -> job record (queued)
//   GET  /api/solves/:id        job status
//   GET  /api/solves/:id/result finished solve JSON (engine output)
//   GET  /api/jobs              all job records this process knows
//   GET  /api/library           finished solves in the data dir
//   GET  /api/library/:id       one library solve JSON
//   GET  /api/preflop/index     preflop range-set index (data/preflop/index.json)
//   GET  /api/preflop/sets/:id  one preflop range set (id must be in the index)
//   GET  /api/preflop/class-table  per-class feature/equity table
//                               (data/preflop/class-table.json, generated by
//                               the engine's build-ranges tool)
//
// Jobs run one at a time (solves are CPU-heavy). The service writes the
// spot JSON to DATA_DIR/jobs/<id>/spot.json, invokes the engine binary
// (solve-river for 5-card boards, solve-turn for 4-card boards, solve-flop
// for 3-card boards) from ENGINE_BIN, and on success copies the result
// into DATA_DIR/library/.
//
// A solve submission may name a preflop range set per side
// (`oop_range_set` / `ip_range_set`, a set id from the preflop index) in
// place of the raw `oop_range` / `ip_range` arrays. The server expands the
// set into per-combo engine range entries (see expandRangeSet below) and
// records the set ids on the job.
//
// NO AUTH: bind to localhost / a private network only. See README.md.

import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { promises as fs } from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PORT = Number(process.env.PORT ?? 8787);
const HOST = process.env.HOST ?? '127.0.0.1';
const DATA_DIR = process.env.DATA_DIR ?? path.join(HERE, 'data');
const PREFLOP_DIR =
  process.env.PREFLOP_DIR ?? path.resolve(HERE, '..', 'data', 'preflop');
const ENGINE_BIN =
  process.env.ENGINE_BIN ?? path.resolve(HERE, '..', 'engine', 'target', 'release');
const MAX_BODY_BYTES = 4 * 1024 * 1024;
const JOB_TIMEOUT_MS = Number(process.env.JOB_TIMEOUT_MS ?? 30 * 60 * 1000);

const JOBS_DIR = path.join(DATA_DIR, 'jobs');
const LIBRARY_DIR = path.join(DATA_DIR, 'library');

/** @type {Map<string, object>} */
const jobs = new Map();
let jobChain = Promise.resolve();

function nowIso() {
  return new Date().toISOString();
}

function boardCardCount(board) {
  if (typeof board !== 'string') return 0;
  return board.split(/[\s,]+/).filter((t) => t.trim().length > 0).length;
}

function kindForBoard(board) {
  const n = boardCardCount(board);
  if (n === 5) return 'river';
  if (n === 4) return 'turn';
  if (n === 3) return 'flop';
  return null;
}

async function writeJobFile(job) {
  const dir = path.join(JOBS_DIR, job.id);
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, 'job.json'), JSON.stringify(job, null, 2));
}

async function runJob(job, spot) {
  job.status = 'running';
  await writeJobFile(job);
  const dir = path.join(JOBS_DIR, job.id);
  const spotPath = path.join(dir, 'spot.json');
  const resultPath = path.join(dir, 'result.json');
  await fs.writeFile(spotPath, JSON.stringify(spot, null, 2));

  const binaryName =
    job.kind === 'flop' ? 'solve-flop' : job.kind === 'turn' ? 'solve-turn' : 'solve-river';
  const binary = path.join(ENGINE_BIN, binaryName);
  try {
    await fs.access(binary);
  } catch {
    job.status = 'error';
    job.error = `Engine binary not found at ${binary}. Build the engine (cargo build --release) or set ENGINE_BIN.`;
    job.finished_at = nowIso();
    await writeJobFile(job);
    return;
  }

  const code = await new Promise((resolve) => {
    const child = spawn(binary, [spotPath, resultPath], { stdio: ['ignore', 'pipe', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', (chunk) => {
      stderr += String(chunk);
    });
    const timer = setTimeout(() => {
      child.kill('SIGKILL');
    }, JOB_TIMEOUT_MS);
    child.on('error', () => {
      clearTimeout(timer);
      resolve(-1);
    });
    child.on('close', (exitCode) => {
      clearTimeout(timer);
      job.stderr_tail = stderr.slice(-2000);
      resolve(exitCode ?? -1);
    });
  });

  if (code !== 0) {
    job.status = 'error';
    job.error = `Engine exited with code ${code}. ${job.stderr_tail ?? ''}`.trim();
    job.finished_at = nowIso();
    await writeJobFile(job);
    return;
  }

  try {
    const raw = await fs.readFile(resultPath, 'utf8');
    const result = JSON.parse(raw);
    job.nash_distance_pct = result?.exploitability?.nash_distance_pct ?? null;
    job.iterations = result?.iterations ?? null;
    job.status = 'done';
    job.finished_at = nowIso();
    // Publish into the library.
    await fs.mkdir(LIBRARY_DIR, { recursive: true });
    await fs.writeFile(path.join(LIBRARY_DIR, `${job.id}.json`), raw);
    await fs.writeFile(
      path.join(LIBRARY_DIR, `${job.id}.meta.json`),
      JSON.stringify(
        {
          id: job.id,
          name: job.name,
          kind: job.kind,
          street: job.kind,
          board: job.board,
          oop_range_set: job.oop_range_set ?? null,
          ip_range_set: job.ip_range_set ?? null,
          nash_distance_pct: job.nash_distance_pct,
          iterations: job.iterations,
          finished_at: job.finished_at,
        },
        null,
        2,
      ),
    );
  } catch (err) {
    job.status = 'error';
    job.error = `Could not read engine result: ${err instanceof Error ? err.message : String(err)}`;
    job.finished_at = nowIso();
  }
  await writeJobFile(job);
}

function publicJob(job) {
  const { stderr_tail, ...rest } = job;
  return rest;
}

async function listLibrary() {
  await fs.mkdir(LIBRARY_DIR, { recursive: true });
  const files = (await fs.readdir(LIBRARY_DIR)).filter(
    (f) => f.endsWith('.json') && !f.endsWith('.meta.json'),
  );
  const items = [];
  for (const file of files) {
    const id = file.replace(/\.json$/, '');
    const full = path.join(LIBRARY_DIR, file);
    try {
      const raw = await fs.readFile(full, 'utf8');
      const result = JSON.parse(raw);
      let meta = {};
      try {
        meta = JSON.parse(await fs.readFile(path.join(LIBRARY_DIR, `${id}.meta.json`), 'utf8'));
      } catch {
        meta = {};
      }
      const stat = await fs.stat(full);
      items.push({
        id,
        name: meta.name ?? `Solve · ${result.board ?? id}`,
        kind: meta.kind ?? meta.street ?? kindForBoard(result.board) ?? 'river',
        board: result.board ?? '',
        oop_range_set: meta.oop_range_set ?? null,
        ip_range_set: meta.ip_range_set ?? null,
        nash_distance_pct:
          result?.exploitability?.nash_distance_pct ?? meta.nash_distance_pct ?? null,
        iterations: result?.iterations ?? meta.iterations ?? null,
        finished_at: meta.finished_at ?? null,
        size_bytes: stat.size,
      });
    } catch {
      // Skip unreadable entries rather than failing the whole list.
    }
  }
  items.sort((a, b) => String(b.finished_at ?? '').localeCompare(String(a.finished_at ?? '')));
  return items;
}

// ---------------------------------------------------------------------------
// Preflop range sets (data/preflop/)
//
// A range set document maps canonical hand-class keys (a representative
// combo whose suits are labelled by first occurrence, e.g. "As Ah Ks Kh")
// to per-action frequencies. The concrete combos of a class are exactly
// the distinct suit-permutation images of the representative: apply all
// 24 permutations of the four suits, normalise each image by sorting its
// cards (rank descending, then suit in s/h/d/c order) and dedupe. The
// size of that set is the class multiplicity — summing it over a real set
// file reproduces the set's combo-weighted action totals exactly (e.g.
// the 6-max BTN RFI set yields 270,725 combos and 49.0% raise).
// ---------------------------------------------------------------------------

const SUIT_ORDER = ['s', 'h', 'd', 'c'];
const RANK_VALUE = {
  A: 14, K: 13, Q: 12, J: 11, T: 10, 9: 9, 8: 8, 7: 7, 6: 6, 5: 5, 4: 4, 3: 3, 2: 2,
};

function suitPermutations() {
  const perms = [];
  const used = [false, false, false, false];
  const current = [];
  const walk = () => {
    if (current.length === 4) {
      perms.push([...current]);
      return;
    }
    for (let i = 0; i < 4; i += 1) {
      if (used[i]) continue;
      used[i] = true;
      current.push(SUIT_ORDER[i]);
      walk();
      current.pop();
      used[i] = false;
    }
  };
  walk();
  return perms;
}
const SUIT_PERMS = suitPermutations();

/** All concrete combos of the class named by a canonical representative key. */
function classCombos(key) {
  const cards = key.split(' ').map((tok) => ({ rank: tok[0], suit: tok[1] }));
  const seen = new Set();
  for (const perm of SUIT_PERMS) {
    const mapping = { s: perm[0], h: perm[1], d: perm[2], c: perm[3] };
    const mapped = cards.map((c) => ({ rank: c.rank, suit: mapping[c.suit] }));
    mapped.sort(
      (a, b) =>
        RANK_VALUE[b.rank] - RANK_VALUE[a.rank] ||
        SUIT_ORDER.indexOf(a.suit) - SUIT_ORDER.indexOf(b.suit),
    );
    seen.add(mapped.map((c) => `${c.rank}${c.suit}`).join(' '));
  }
  return [...seen];
}

function formatWeight(freq) {
  return String(Number(freq.toFixed(6)));
}

class HttpError extends Error {
  constructor(status, message) {
    super(message);
    this.status = status;
  }
}

/** @type {object | null} */
let preflopIndexCache = null;
/** @type {Map<string, object>} */
const preflopSetCache = new Map();

async function loadPreflopIndex() {
  if (preflopIndexCache) return preflopIndexCache;
  let parsed;
  try {
    parsed = JSON.parse(await fs.readFile(path.join(PREFLOP_DIR, 'index.json'), 'utf8'));
  } catch {
    throw new HttpError(500, `Preflop index not readable at ${path.join(PREFLOP_DIR, 'index.json')}`);
  }
  if (!parsed || !Array.isArray(parsed.rangesets)) {
    throw new HttpError(500, 'Preflop index is malformed (no rangesets array)');
  }
  preflopIndexCache = parsed;
  return parsed;
}

async function findPreflopSetEntry(id) {
  const index = await loadPreflopIndex();
  return index.rangesets.find((entry) => entry && entry.id === id) ?? null;
}

/** Resolve an index entry's path inside PREFLOP_DIR (never user-controlled). */
function preflopEntryPath(entry) {
  const resolved = path.resolve(PREFLOP_DIR, String(entry.path ?? ''));
  if (!resolved.startsWith(PREFLOP_DIR + path.sep)) return null;
  return resolved;
}

async function loadPreflopSet(id) {
  if (preflopSetCache.has(id)) return preflopSetCache.get(id);
  const entry = await findPreflopSetEntry(id);
  if (!entry) {
    throw new HttpError(400, `Unknown preflop range set id "${id}" (not in the preflop index)`);
  }
  const file = preflopEntryPath(entry);
  if (!file) throw new HttpError(500, `Preflop index entry for "${id}" has an unsafe path`);
  let doc;
  try {
    doc = JSON.parse(await fs.readFile(file, 'utf8'));
  } catch {
    throw new HttpError(500, `Preflop range set "${id}" is not readable at ${file}`);
  }
  if (!doc || typeof doc.hands !== 'object' || doc.hands === null) {
    throw new HttpError(500, `Preflop range set "${id}" is malformed (no hands object)`);
  }
  preflopSetCache.set(id, doc);
  return doc;
}

/**
 * The action whose frequencies define the continuing range when a set is
 * loaded into a solve. v1 supports exactly the contexts where that range
 * is well-defined:
 *   - `rfi` sets:    the opening range = hands' `raise` frequencies.
 *   - `vs_rfi` sets: the continuing range vs an open = hands' `call`
 *                    frequencies (the 3-bet slice is a different, narrower
 *                    range and is NOT silently substituted).
 * Any other context (sb_play, three_bet, ...) is rejected with 422.
 */
function solveActionForSet(doc) {
  if (doc.context === 'rfi') return 'raise';
  if (doc.context === 'vs_rfi') return 'call';
  return null;
}

/**
 * Expand a range set into engine range entries ("As Ah Kd Qc:0.5", ...).
 * Every concrete combo of a class gets the class's frequency for the
 * set's solve action; classes with zero frequency for that action are
 * omitted. Returns { range, action, combos }.
 */
async function expandRangeSet(id) {
  const doc = await loadPreflopSet(id);
  const action = solveActionForSet(doc);
  if (action === null) {
    throw new HttpError(
      422,
      `Preflop range set "${id}" has context "${doc.context}", which cannot feed a solve in v1. ` +
        'Only RFI sets (their raise range) and vs-RFI sets (their call range) have a well-defined continuing range.',
    );
  }
  const range = [];
  for (const [key, actions] of Object.entries(doc.hands)) {
    const freq = actions && typeof actions === 'object' ? actions[action] : undefined;
    if (typeof freq !== 'number' || !(freq > 0)) continue;
    const weight = formatWeight(freq);
    for (const combo of classCombos(key)) {
      range.push(`${combo}:${weight}`);
    }
  }
  if (range.length === 0) {
    throw new HttpError(422, `Preflop range set "${id}" expands to an empty ${action} range`);
  }
  return { range, action, combos: range.length };
}

/** Serve a JSON file verbatim with a JSON content type. */
async function sendJsonFile(res, file) {
  let raw;
  try {
    raw = await fs.readFile(file, 'utf8');
  } catch {
    sendJson(res, 404, { error: `Not found: ${path.basename(file)}` });
    return;
  }
  res.writeHead(200, {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
  });
  res.end(raw);
}

function sendJson(res, status, body) {
  const text = JSON.stringify(body);
  res.writeHead(status, {
    'Content-Type': 'application/json',
    'Content-Length': Buffer.byteLength(text),
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
  });
  res.end(text);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    let total = 0;
    req.on('data', (chunk) => {
      total += chunk.length;
      if (total > MAX_BODY_BYTES) {
        reject(new Error('Request body too large'));
        req.destroy();
        return;
      }
      chunks.push(chunk);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url ?? '/', `http://${req.headers.host ?? 'localhost'}`);
  const parts = url.pathname.split('/').filter((p) => p.length > 0);
  try {
    if (req.method === 'OPTIONS') {
      res.writeHead(204, {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
      });
      res.end();
      return;
    }

    if (req.method === 'POST' && url.pathname === '/api/solves') {
      const text = await readBody(req);
      let spot;
      try {
        spot = JSON.parse(text);
      } catch {
        sendJson(res, 400, { error: 'Body must be valid JSON (an engine spot).' });
        return;
      }
      const kind = kindForBoard(spot?.board);
      if (kind === null) {
        sendJson(res, 400, { error: 'Spot board must have 3, 4 or 5 cards.' });
        return;
      }
      // Optional range-set loading: `oop_range_set` / `ip_range_set` name a
      // preflop set id and replace the raw range array for that side. The
      // expansion happens here, server-side; the engine only ever sees
      // ordinary per-combo range entries.
      const rangeSets = { oop: null, ip: null };
      try {
        for (const side of ['oop', 'ip']) {
          const setId = spot[`${side}_range_set`];
          if (setId === undefined || setId === null) continue;
          if (typeof setId !== 'string' || setId.length === 0) {
            throw new HttpError(400, `${side}_range_set must be a preflop range set id string`);
          }
          if (spot[`${side}_range`] !== undefined || spot[side] !== undefined) {
            throw new HttpError(
              400,
              `Provide either ${side}_range or ${side}_range_set for the ${side.toUpperCase()} side, not both`,
            );
          }
          const expanded = await expandRangeSet(setId);
          spot[`${side}_range`] = expanded.range;
          rangeSets[side] = setId;
          delete spot[`${side}_range_set`];
        }
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      const job = {
        id: randomUUID().slice(0, 8),
        status: 'queued',
        kind,
        board: spot.board,
        name: `Custom solve · ${spot.board}`,
        oop_range_set: rangeSets.oop,
        ip_range_set: rangeSets.ip,
        created_at: nowIso(),
        finished_at: null,
        nash_distance_pct: null,
        iterations: null,
        error: null,
      };
      jobs.set(job.id, job);
      await writeJobFile(job);
      // Serial queue: one solve at a time.
      jobChain = jobChain.then(() => runJob(job, spot)).catch(() => undefined);
      sendJson(res, 202, publicJob(job));
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'solves' && parts[2]) {
      const job = jobs.get(parts[2]);
      if (!job) {
        sendJson(res, 404, { error: 'Unknown job id' });
        return;
      }
      if (parts[3] === 'result') {
        if (job.status !== 'done') {
          sendJson(res, 409, { error: `Job is ${job.status}, no result yet` });
          return;
        }
        const raw = await fs.readFile(path.join(JOBS_DIR, job.id, 'result.json'), 'utf8');
        res.writeHead(200, {
          'Content-Type': 'application/json',
          'Access-Control-Allow-Origin': '*',
        });
        res.end(raw);
        return;
      }
      sendJson(res, 200, publicJob(job));
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/jobs') {
      sendJson(res, 200, { jobs: [...jobs.values()].map(publicJob) });
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/library') {
      sendJson(res, 200, { library: await listLibrary() });
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'library' && parts[2]) {
      if (!/^[A-Za-z0-9_-]+$/.test(parts[2])) {
        sendJson(res, 400, { error: 'Bad library id' });
        return;
      }
      const file = path.join(LIBRARY_DIR, `${parts[2]}.json`);
      try {
        const raw = await fs.readFile(file, 'utf8');
        res.writeHead(200, {
          'Content-Type': 'application/json',
          'Access-Control-Allow-Origin': '*',
        });
        res.end(raw);
      } catch {
        sendJson(res, 404, { error: 'Unknown library id' });
      }
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/preflop/index') {
      await sendJsonFile(res, path.join(PREFLOP_DIR, 'index.json'));
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/preflop/class-table') {
      const file = path.join(PREFLOP_DIR, 'class-table.json');
      try {
        await fs.access(file);
      } catch {
        sendJson(res, 404, {
          error:
            'Class table not generated yet: data/preflop/class-table.json is written by the engine build-ranges tool on a host.',
        });
        return;
      }
      await sendJsonFile(res, file);
      return;
    }

    if (req.method === 'GET' && parts[0] === 'api' && parts[1] === 'preflop' && parts[2] === 'sets' && parts[3]) {
      let entry;
      try {
        entry = await findPreflopSetEntry(parts[3]);
      } catch (err) {
        if (err instanceof HttpError) {
          sendJson(res, err.status, { error: err.message });
          return;
        }
        throw err;
      }
      if (!entry) {
        sendJson(res, 404, { error: `Unknown preflop range set id "${parts[3]}"` });
        return;
      }
      const file = preflopEntryPath(entry);
      if (!file) {
        sendJson(res, 500, { error: `Preflop index entry for "${parts[3]}" has an unsafe path` });
        return;
      }
      await sendJsonFile(res, file);
      return;
    }

    if (req.method === 'GET' && url.pathname === '/api/health') {
      sendJson(res, 200, { ok: true, engine_bin: ENGINE_BIN, data_dir: DATA_DIR, preflop_dir: PREFLOP_DIR });
      return;
    }

    sendJson(res, 404, { error: 'Not found' });
  } catch (err) {
    sendJson(res, 500, { error: err instanceof Error ? err.message : 'Internal error' });
  }
});

await fs.mkdir(JOBS_DIR, { recursive: true });
await fs.mkdir(LIBRARY_DIR, { recursive: true });
server.listen(PORT, HOST, () => {
  console.log(`plo-api listening on http://${HOST}:${PORT}`);
  console.log(`  ENGINE_BIN=${ENGINE_BIN}`);
  console.log(`  DATA_DIR=${DATA_DIR}`);
});
