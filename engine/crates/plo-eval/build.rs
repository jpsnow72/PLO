use std::env;
use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    // Step 1: Find 13 rank weights W[0..13] such that all 6,175 5-card rank multisets
    // (with sum(counts) == 5 and 0 <= count[r] <= 4) have unique sums sum(count[r] * W[r]).
    let mut weights = [0u32; 13];
    // (size, sum) for all valid multisets of size 0..=4 on ranks 0..k
    let mut multisets_le4: Vec<(u8, u32)> = vec![(0, 0)];
    let mut used_5: Vec<bool> = Vec::new();
    let mut max_5_sum = 0u32;

    for k in 0..13 {
        let mut w = if k == 0 { 0 } else { weights[k - 1] + 1 };
        if k > 0 {
            'candidate: loop {
                // Check if `w` produces any collision among new 5-card sums or with existing `used_5`.
                let mut new_sums = Vec::with_capacity(multisets_le4.len());
                for &(sz, base_sum) in &multisets_le4 {
                    if sz == 0 {
                        continue; // m = 5 copies of a single rank is impossible in a 4-suit deck
                    }
                    let m = (5 - sz) as u32; // m in 1..=4
                    let s = base_sum + m * w;
                    if (s as usize) < used_5.len() && used_5[s as usize] {
                        w += 1;
                        continue 'candidate;
                    }
                    new_sums.push(s);
                }
                new_sums.sort_unstable();
                for pair in new_sums.windows(2) {
                    if pair[0] == pair[1] {
                        w += 1;
                        continue 'candidate;
                    }
                }
                // Found valid weight `w`!
                for s in new_sums {
                    if s > max_5_sum {
                        max_5_sum = s;
                    }
                    if (s as usize) >= used_5.len() {
                        used_5.resize((s as usize) + 1, false);
                    }
                    used_5[s as usize] = true;
                }
                break;
            }
        }

        weights[k] = w;

        // Expand `multisets_le4` with 1..=4 copies of rank `k` where new_size <= 4
        let prev_len = multisets_le4.len();
        for idx in 0..prev_len {
            let (sz, base_sum) = multisets_le4[idx];
            for m in 1..=4u8 {
                if sz + m <= 4 {
                    multisets_le4.push((sz + m, base_sum + (m as u32) * w));
                }
            }
        }
    }

    let flush_base = max_5_sum + 1;
    let table_len = (flush_base as usize) + 8192;

    // Step 2: Build SUIT_KEY[8192]
    // For a 13-bit suit rank mask `m`:
    // - if popcnt(m) <= 4: sum of W[r] for set bits `r` in `m`
    // - if popcnt(m) == 5: flush_base + m (since in a 5-card hand, popcnt == 5 means the other 3 suits are 0)
    let mut suit_key = [0u32; 8192];
    for m in 1..8192usize {
        let ones = m.count_ones();
        if ones <= 4 {
            let mut sum = 0u32;
            for r in 0..13 {
                if ((m >> r) & 1) != 0 {
                    sum += weights[r];
                }
            }
            suit_key[m] = sum;
        } else if ones == 5 {
            suit_key[m] = flush_base + (m as u32);
        }
    }

    // Step 3: Populate EVAL_TABLE
    let mut eval_table = vec![0u32; table_len];
    let mut counts = [0u8; 13];
    let mut multiset_count = 0usize;
    populate_non_flush(
        0,
        5,
        &mut counts,
        &weights,
        &mut eval_table,
        &mut multiset_count,
    );
    assert_eq!(
        multiset_count, 6175,
        "Expected exactly 6,175 5-card rank multisets"
    );

    // Populate flush entries
    let mut flush_count = 0usize;
    for m in 0..8192usize {
        if m.count_ones() == 5 {
            eval_table[(flush_base as usize) + m] = score_flush_mask(m as u16);
            flush_count += 1;
        }
    }
    assert_eq!(flush_count, 1287, "Expected C(13,5) = 1,287 flush masks");

    // Step 4: Write generated tables to $OUT_DIR/eval_tables.rs
    let out_dir = env::var_os("OUT_DIR").expect("OUT_DIR not set");
    let dest_path = Path::new(&out_dir).join("eval_tables.rs");
    let mut out = BufWriter::new(File::create(dest_path).expect("failed to create eval_tables.rs"));

    writeln!(out, "// Auto-generated by build.rs — do not edit.").unwrap();
    writeln!(out, "pub const RANK_WEIGHTS: [u32; 13] = {:?};", weights).unwrap();
    writeln!(out, "pub const FLUSH_BASE: u32 = {};", flush_base).unwrap();
    writeln!(out, "pub static SUIT_KEY: [u32; 8192] = {:?};", suit_key).unwrap();
    writeln!(
        out,
        "pub static EVAL_TABLE: [u32; {}] = {:?};",
        eval_table.len(),
        eval_table
    )
    .unwrap();
}

fn populate_non_flush(
    rank_idx: usize,
    remaining: u8,
    counts: &mut [u8; 13],
    weights: &[u32; 13],
    eval_table: &mut [u32],
    multiset_count: &mut usize,
) {
    if rank_idx == 13 {
        if remaining == 0 {
            let mut key = 0u32;
            for r in 0..13 {
                key += (counts[r] as u32) * weights[r];
            }
            assert_eq!(
                eval_table[key as usize], 0,
                "Collision detected at key {}",
                key
            );
            eval_table[key as usize] = score_non_flush_counts(counts);
            *multiset_count += 1;
        }
        return;
    }

    let max_c = remaining.min(4);
    for c in 0..=max_c {
        counts[rank_idx] = c;
        populate_non_flush(
            rank_idx + 1,
            remaining - c,
            counts,
            weights,
            eval_table,
            multiset_count,
        );
    }
    counts[rank_idx] = 0;
}

fn score_non_flush_counts(counts: &[u8; 13]) -> u32 {
    // Group ranks by (multiplicity desc, rank desc)
    let mut groups: Vec<(u8, u32)> = Vec::new();
    for r in (0..13).rev() {
        if counts[r] > 0 {
            groups.push((counts[r], r as u32));
        }
    }
    groups.sort_by(|a, b| b.0.cmp(&a.0).then_with(|| b.1.cmp(&a.1)));

    match groups.as_slice() {
        // Four of a Kind: (4, 1)
        &[(4, quad), (1, kicker)] => (7 << 20) | (quad << 16) | (kicker << 12),
        // Full House: (3, 2)
        &[(3, trips), (2, pair)] => (6 << 20) | (trips << 16) | (pair << 12),
        // Three of a Kind: (3, 1, 1)
        &[(3, trips), (1, k1), (1, k2)] => (3 << 20) | (trips << 16) | (k1 << 12) | (k2 << 8),
        // Two Pair: (2, 2, 1)
        &[(2, hp), (2, lp), (1, k)] => (2 << 20) | (hp << 16) | (lp << 12) | (k << 8),
        // One Pair: (2, 1, 1, 1)
        &[(2, pair), (1, k1), (1, k2), (1, k3)] => {
            (1 << 20) | (pair << 16) | (k1 << 12) | (k2 << 8) | (k3 << 4)
        }
        // 5 distinct ranks: Straight or High Card
        &[(1, r0), (1, r1), (1, r2), (1, r3), (1, r4)] => {
            if r0 - r4 == 4 {
                // Normal straight
                (4 << 20) | (r0 << 16)
            } else if r0 == 12 && r1 == 3 && r2 == 2 && r3 == 1 && r4 == 0 {
                // Wheel straight (A-2-3-4-5, 5-high)
                (4 << 20) | (3 << 16)
            } else {
                // High Card
                (0 << 20) | (r0 << 16) | (r1 << 12) | (r2 << 8) | (r3 << 4) | r4
            }
        }
        _ => unreachable!("Invalid 5-card rank distribution"),
    }
}

fn score_flush_mask(mask: u16) -> u32 {
    let mut ranks = [0u32; 5];
    let mut idx = 0;
    for r in (0..13).rev() {
        if ((mask >> r) & 1) != 0 {
            ranks[idx] = r as u32;
            idx += 1;
        }
    }
    let [r0, r1, r2, r3, r4] = ranks;
    if r0 - r4 == 4 {
        // Straight Flush
        (8 << 20) | (r0 << 16)
    } else if r0 == 12 && r1 == 3 && r2 == 2 && r3 == 1 && r4 == 0 {
        // Steel Wheel Straight Flush (A-2-3-4-5 suited, 5-high)
        (8 << 20) | (3 << 16)
    } else {
        // Flush
        (5 << 20) | (r0 << 16) | (r1 << 12) | (r2 << 8) | (r3 << 4) | r4
    }
}
